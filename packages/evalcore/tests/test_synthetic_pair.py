def _confidence(edit_distance: int, key_length: int) -> str:
    value = (Decimal(edit_distance) / Decimal(key_length)).quantize(
        Decimal("0.0001"), ROUND_HALF_EVEN
    )
    return format(value.normalize(), "f")


@pytest.mark.parametrize("variant", ["base", "empty_chunk"])
def test_synthetic_expected_results_are_self_consistent(variant: str) -> None:
    want = expected_variant(variant)
    spans = want["spans"]
    alignment = want["alignment"]
    hits, subs, dels, ins = (
        alignment["hits"],
        alignment["substitutions"],
        alignment["deletions"],
        alignment["insertions"],
    )
    assert hits + subs + dels == EXPORT_TOKENS == expected()["export_tokens"]
    assert hits + subs + ins == want["stt_tokens"]
    assert want["edits"] == subs + dels + ins
    assert want["mer_fraction"] == f"{want['edits']}/{hits + want['edits']}"
    assert sum(s["substitutions"] for s in spans) == subs
    assert sum(s["deletions"] for s in spans) == dels
    assert sum(s["insertions"] for s in spans) == ins
    flagged = [s for s in spans if s["flagged"]]
    assert want["flag_count"] == len(flagged)
    tokens = sum(s["export_tokens"] for s in flagged)
    assert want["flagged_export_tokens"] == tokens
    assert want["flagged_share_fraction"] == f"{tokens}/{EXPORT_TOKENS}"
    ordered = sorted(
        spans, key=lambda s: (s["turn_seq"], s["start"], s["end"], s["stt_token_start"])
    )
    assert spans == ordered
    for span in spans:
        assert span["export_tokens"] == span["substitutions"] + span["deletions"]
        assert 0 < span["edit_distance"] <= span["key_length"]
        assert span["confidence"] == _confidence(span["edit_distance"], span["key_length"])
        # threshold 0.5 from the example rubric file: edit_distance >= 0.5 * key_length
        assert span["flagged"] == (2 * span["edit_distance"] >= span["key_length"]), span["id"]
        assert (span["start"] == span["end"]) == (span["export_tokens"] == 0)
        assert (
            span["stt_token_end"] - span["stt_token_start"]
            == span["substitutions"] + span["insertions"]
        )
        assert ("audio_start_ms" in span) == ("audio_end_ms" in span)
    assert want["evidence_turn_seqs"] == sorted({s["turn_seq"] for s in flagged})
    ranges: list[list[int]] = []
    for span in flagged:
        if "audio_start_ms" in span:
            pair = [span["audio_start_ms"], span["audio_end_ms"]]
            if pair not in ranges:
                ranges.append(pair)
    assert want["evidence_audio_ranges_ms"] == ranges
    assert want["share_passed"] is True  # budget 1.0 inclusive: the rule cannot fail
    if variant == "base":
        assert want["turns_with_a_flag"] == len(want["evidence_turn_seqs"])
        assert want["flagged_share_value"] == tokens / EXPORT_TOKENS


def test_synthetic_planted_differences_hold_in_the_expected_base_spans() -> None:
    spans = expected_spans("base")
    checks = expected_variant("base")["planted_checks"]
    assert [c["id"] for c in checks] == list(PLANTED_IDS)
    readme = data_path("README.md").read_text("utf-8")
    for planted in PLANTED_IDS:
        assert f"| {planted} |" in readme
    for check in checks:
        in_turn = [s for s in spans if s["turn_seq"] == check["turn_seq"]]
        if check["expect"] == "no_span_in_turn":
            assert not in_turn, check["id"]
            continue
        hit = [s for s in in_turn if (s["start"], s["end"]) == (check["start"], check["end"])]
        assert len(hit) == 1, check["id"]
        assert hit[0]["flagged"] == (check["expect"] == "flagged_span"), check["id"]
    # the three outcomes the README names: flagged, recorded but not flagged, and no span
    assert {c["expect"] for c in checks} == {"no_span_in_turn", "flagged_span", "unflagged_span"}


