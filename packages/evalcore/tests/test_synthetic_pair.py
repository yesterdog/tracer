@pytest.mark.parametrize("variant", ["base", "empty_chunk"])
def test_synthetic_expectations_match_an_independent_alignment(variant: str) -> None:
    """The expected counts and span boundaries equal a from-scratch second implementation."""
    summary = independent_summary(variant)
    want = expected_variant(variant)
    assert summary.export_tokens == EXPORT_TOKENS
    assert summary.stt_tokens == want["stt_tokens"]
    assert (summary.hits, summary.substitutions, summary.deletions, summary.insertions) == (
        want["alignment"]["hits"],
        want["alignment"]["substitutions"],
        want["alignment"]["deletions"],
        want["alignment"]["insertions"],
    )
    spans = expected_spans(variant)
    with_tokens = [
        (
            s["turn_seq"],
            s["start"],
            s["end"],
            s["export_tokens"],
            s["substitutions"],
            s["deletions"],
        )
        for s in spans
        if s["export_tokens"] > 0
    ]
    found = [
        (s.turn_seq, s.start, s.end, s.export_tokens, s.substitutions, s.deletions)
        for s in summary.spans
    ]
    assert found == with_tokens
    assert summary.insertion_only_runs == len([s for s in spans if s["export_tokens"] == 0])


def _cost(ops: list[tuple[str, int | None, int | None]]) -> tuple[int, int]:
    """The cost pair (edits, deletions plus insertions) of an op list."""
    edits = sum(1 for op in ops if op[0] != "M")
    return edits, sum(1 for op in ops if op[0] in {"D", "I"})


def test_synthetic_empty_chunk_tie_is_real_and_broken_by_the_latest_feasible_word() -> None:
    """The empty-chunk placement is a tie among equal-cost alignments, decided by the backtrace.

    The hand prediction (the three matched words of the STT tail at the start of turn 7, export
    tokens 42 to 44) has the same cost pair as the placement the pipeline's rule gives (export
    tokens 63, 64 and 68). Only the rule (match, substitution, deletion, insertion, from the end)
    selects the latest feasible export word for each STT word.
    """
    from tracer_evalcore.tokens import TextTurn, tokenise_turns

    summary = independent_summary("empty_chunk")
    ops = list(summary.ops)
    export = tokenise_turns(
        [TextTurn(seq=i, text=t) for i, (_s, t) in enumerate(export_lines())], "mr-Deva/1"
    )
    stt = tokenise_turns(
        [TextTurn(seq=i, text=t) for i, t in enumerate(stt_texts("empty_chunk"))], "mr-Deva/1"
    )
    # the placement: one substitution on the last word of the stretch, the STT tail words matched
    # to the last feasible occurrences before it
    assert [op for op in ops if op[0] == "S" and op[2] == 44] == [("S", 87, 44)]
    assert [op[1] for op in ops if op[0] == "M" and op[2] in (41, 42, 43)] == [63, 64, 68]
    # an equally cheap alignment exists that matches the first occurrences (export 42, 43, 44)
    hand: list[tuple[str, int, int | None]] = [("M", 42, 41), ("M", 43, 42), ("M", 44, 43)]
    hand += [("D", i, None) for i in range(45, 87)]
    hand += [("S", 87, 44)]
    for _kind, i, j in hand:
        if _kind == "M":
            assert i is not None
            assert j is not None
            assert export.keys[i] == stt.keys[j]
    head = [op for op in ops if op[1] is not None and op[1] < 42]
    head += [op for op in ops if op[1] is None and op[2] is not None and op[2] < 41]
    tail = [op for op in ops if op[1] is not None and op[1] >= 88]
    tail += [op for op in ops if op[1] is None and op[2] is not None and op[2] >= 45]
    alternative = sorted(
        [*head, *hand, *tail],
        key=lambda op: (op[1] if op[1] is not None else -1, op[2] if op[2] is not None else -1),
    )
    assert {op for op in alternative if op[0] == "M"} != {op for op in ops if op[0] == "M"}
    assert sorted(op[1] for op in alternative if op[1] is not None) == list(range(EXPORT_TOKENS))
    assert sorted(op[2] for op in alternative if op[2] is not None) == list(range(len(stt.keys)))
    assert _cost(alternative) == _cost(ops) == (48, 44)


