def test_synthetic_wav_recipe_segments_tile_the_recording() -> None:
    spec = recipe()
    assert (spec["sample_rate_hz"], spec["channels"], spec["sample_width_bytes"]) == (24000, 1, 2)
    assert spec["total_frames"] == 1_632_000  # 68.00 s
    segments = spec["segments"]
    assert segments[0]["start_frame"] == 0
    assert segments[-1]["end_frame"] == spec["total_frames"]
    for before, after in pairwise(segments):
        assert before["end_frame"] == after["start_frame"]
        assert before["kind"] != after["kind"]
    assert all(s["end_frame"] > s["start_frame"] for s in segments)
    assert all(s["amplitude"] == 8000 for s in segments if s["kind"] == "tone")


def test_synthetic_generated_wav_has_exact_zero_silences_and_audible_tones(
    synthetic_wav: Path,
) -> None:
    import wave
    from array import array

    spec = recipe()
    with wave.open(str(synthetic_wav), "rb") as handle:
        assert handle.getnchannels() == 1
        assert handle.getsampwidth() == 2
        assert handle.getframerate() == 24000
        assert handle.getnframes() == spec["total_frames"]
        pcm = array("h")
        pcm.frombytes(handle.readframes(handle.getnframes()))
    assert synthetic_wav.stat().st_size == 44 + 2 * spec["total_frames"]
    for segment in spec["segments"]:
        window = pcm[segment["start_frame"] : segment["end_frame"]]
        if segment["kind"] == "silence":
            assert not any(window), segment
        else:
            assert max(window) > 7000, segment
            assert min(window) < -7000, segment
            assert max(abs(v) for v in window) <= segment["amplitude"]


def test_synthetic_chunk_plan_matches_the_real_chunker_on_the_generated_wav(
    synthetic_wav: Path,
) -> None:
    from tracer_evalcore.audio.chunker import chunk_wav
    from tracer_evalcore.importers.wav import read_wav
    from tracer_evalschema.privacy import ConsentRecord, RetentionPolicy

    audio = read_wav(
        synthetic_wav,
        created_at=NOW,
        consent=ConsentRecord(status="unknown"),
        retention=RetentionPolicy(delete_on_expiry=False),
    )
    plan = chunk_wav(audio)
    wanted = chunk_plan()
    assert plan.total_frames == wanted["total_frames"]
    assert [(c.index, c.start_frame, c.end_frame, c.frames) for c in plan.chunks] == [
        (c["index"], c["start_frame"], c["end_frame"], c["frames"]) for c in wanted["chunks"]
    ]
    assert [len(c.wav) for c in plan.chunks] == [c["wav_bytes"] for c in wanted["chunks"]]
    assert plan.as_metadata() == wanted["as_metadata"]
    # the chunks cover every sample exactly once and never exceed the 25 s window
    assert sum(c.frames for c in plan.chunks) == wanted["total_frames"]
    assert all(c.frames <= 600_000 for c in plan.chunks)
    # the 22.99 s, 22.99 s and 22.02 s durations (exact, in frames)
    assert [c.frames for c in plan.chunks] == [551_760, 551_760, 528_480]


