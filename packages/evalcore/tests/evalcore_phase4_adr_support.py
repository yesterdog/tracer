def items_of(spec: AdrSpec, text: str) -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    """(rules, invariants) of one ADR text, each as (label, body)."""
    if spec.amendment:
        section = heading_section(text, AMENDMENT_HEADING, prefix=True)
        head, sep, inv = section.partition("\n" + AMENDMENT_INVARIANTS)
        assert sep, f"ADR {spec.key}: no {AMENDMENT_INVARIANTS!r} subsection"
        return numbered(head, r"(A\d+)\. \*\*"), numbered(inv, r"- (IA\d+)\. ")
    rules = numbered(heading_section(text, "## Decision"), r"(\d+)\. \*\*")
    invariants = numbered(heading_section(text, "## Invariants (testable)"), r"- (I\d+)\. ")
    return rules, invariants


def check_adr(
    spec: AdrSpec,
    text: str,
    *,
    defined: set[str],
    pending: frozenset[str],
    scope: set[str],
) -> list[str]:
    """Every reason why the ADR text breaks the machine-read rule; an empty list means it holds.

    The rule (ADR 0026 to 0029 "Decision", and the amendment paragraphs of ADRs 0023 and 0024):
    the labels run 1..N with the pinned counts; every rule and every invariant cites at least one
    test name in backticks; a cited name is defined by a ``packages/*/tests`` file or is on the
    pending set; the pending set holds only names SCOPE section A names, only names the ADR still
    cites, and no name that a test defines (a name that landed leaves the set).
    """
    problems: list[str] = []
    try:
        rules, invariants = items_of(spec, text)
    except AssertionError as error:
        return [str(error)]
    adr = f"ADR {spec.key}"
    if [label for label, _ in rules] != spec.rule_labels:
        got = [label for label, _ in rules]
        problems.append(
            f"{adr}: rule labels {got} are not {spec.rule_labels[0]}..{spec.rule_labels[-1]}"
        )
    if [label for label, _ in invariants] != spec.invariant_labels:
        got = [label for label, _ in invariants]
        problems.append(f"{adr}: invariant labels {got} are not the expected {spec.invariants}")
    in_items: set[str] = set()
    for kind, group in (("rule", rules), ("invariant", invariants)):
        for label, body in group:
            names = cited(body)
            in_items |= names
            if not names:
                problems.append(f"{adr} {kind} {label} cites no test")
            for name in sorted(names - defined - pending):
                problems.append(
                    f"{adr} {kind} {label} cites {name}: no test defines it, not pending"
                )
            for name in sorted(n for n in names if not re.fullmatch(r"test_[a-z0-9_]+", n)):
                problems.append(f"{adr} {kind} {label} cites {name}, which breaks the naming rule")
    for name in sorted(pending - scope):
        problems.append(f"{adr}: pending {name} is not named by SCOPE section A")
    for name in sorted(pending - in_items):
        problems.append(f"{adr}: pending {name} is no longer cited by a rule or invariant (stale)")
    for name in sorted(pending & defined):
        problems.append(f"{adr}: {name} exists now; remove it from the pending set")
    if spec.self_test is not None:
        if spec.self_test not in defined:
            problems.append(f"{adr}: its own test {spec.self_test} is not defined")
        if not invariants or spec.self_test not in cited(invariants[-1][1]):
            problems.append(f"{adr}: the last invariant does not cite {spec.self_test}")
    return problems


def check_adr_file(key: str) -> list[str]:
    spec = SPECS[key]
    return check_adr(
        spec,
        spec.path.read_text("utf-8"),
        defined=defined_tests(),
        pending=PENDING[key],
        scope=scope_names(),
    )


