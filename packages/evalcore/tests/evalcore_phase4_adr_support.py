def defined_tests(packages: Path | None = None) -> set[str]:
    return set(_defined_tests(str(packages or PACKAGES)))


@functools.cache
def _defined_tests(packages: str) -> frozenset[str]:
    names: set[str] = set()
    for path in sorted(Path(packages).glob("*/tests/test_*.py")):
        tree = ast.parse(path.read_text("utf-8"))
        names |= {
            node.name
            for node in ast.walk(tree)
            if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef)
            and node.name.startswith("test_")
        }
    return frozenset(names)


def cited(text: str) -> set[str]:
    return set(re.findall(r"`(test_\w+)`", text))


def heading_section(text: str, heading: str, *, prefix: bool = False) -> str:
    """The text under the one line ``heading``, up to the next line that starts with ``## ``.

    The match is anchored to a whole line, so a heading quoted inside a rule never matches. A
    ``### `` subsection stays inside. Raises ``AssertionError`` if the heading is absent or twice.
    """
    pattern = re.escape(heading) + (r".*" if prefix else r"") + r"[ \t]*$"
    found = list(re.finditer(rf"^{pattern}", text, re.MULTILINE))
    assert len(found) == 1, f"heading {heading!r}: {len(found)} matches, expected 1"
    rest = text[found[0].end() :]
    end = re.search(r"\n## ", rest)
    return rest[: end.start()] if end else rest


def numbered(section: str, pattern: str) -> list[tuple[str, str]]:
    """(label, text) of each item that starts a line with ``pattern``, up to the next one."""
    starts = list(re.finditer(rf"^{pattern}", section, re.MULTILINE))
    items = []
    for i, match in enumerate(starts):
        end = starts[i + 1].start() if i + 1 < len(starts) else len(section)
        items.append((match.group(1), section[match.start() : end]))
    return items


def scope_section_a() -> str:
    text = SCOPE4.read_text("utf-8")
    start = text.index("## A. Task table")
    end = re.search(r"^## B\. ", text[start:], re.MULTILINE)
    assert end is not None, "SCOPE has no section B after section A"
    return text[start : start + end.start()]


def scope_names() -> set[str]:
    return cited(scope_section_a())


