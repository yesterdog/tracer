@dataclass(frozen=True)
class Reading:
    """One text the whole-ADR reader checks: its full text and the part inside rules."""

    label: str
    full: str
    in_items: str
    #: part of the text whose undefined names need only SCOPE section A (a section a later task
    #: completes: the dialect specifications of ADR 0026)
    lenient: str = ""


def adr_number(path: Path) -> int:
    match = re.match(r"(\d{4})-", path.name)
    assert match is not None, path.name
    return int(match.group(1))


def later_adr_paths() -> list[Path]:
    return sorted(p for p in ADR_DIR.glob("[0-9][0-9][0-9][0-9]-*.md") if adr_number(p) >= 26)


def readings() -> list[Reading]:
    out: list[Reading] = []
    for path in later_adr_paths():
        text = path.read_text("utf-8")
        number = adr_number(path)
        key = f"{number:04d}"
        lenient = ""
        if key in SPECS:
            rules, invariants = items_of(SPECS[key], text)
            body = "\n".join(b for _, b in rules + invariants)
        else:
            body = ""
        if key == "0026":
            lenient = heading_section(text, DIALECT_HEADING)
        out.append(Reading(f"ADR {key}", text, body, lenient))
    for key, path in (("0024A", ADR24), ("0023A", ADR23)):
        section = heading_section(path.read_text("utf-8"), AMENDMENT_HEADING, prefix=True)
        rules, invariants = items_of(SPECS[key], path.read_text("utf-8"))
        out.append(Reading(f"ADR {key}", section, "\n".join(b for _, b in rules + invariants)))
    d11, i43 = adr04_items(ADR04.read_text("utf-8"))
    out.append(Reading("ADR 0004", d11 + "\n" + i43, d11 + "\n" + i43))
    return out


def whole_adr_problems(
    reads: Iterable[Reading],
    *,
    defined: set[str],
    pending: dict[str, frozenset[str]],
    outside: frozenset[str],
    scope: set[str],
    scope_text: str,
) -> list[str]:
    problems: list[str] = []
    all_pending = set().union(*pending.values()) if pending else set()
    for read in reads:
        in_items = cited(read.in_items)
        key = read.label.removeprefix("ADR ")
        for name in sorted(cited(read.full)):
            if name in defined or name in all_pending or name in outside:
                continue
            if name in cited(read.lenient) and name in scope:
                continue
            if name in RENAMED and name not in in_items:
                new = RENAMED[name]
                if name in scope_text and f"`{new}`" in scope_text:
                    continue
                problems.append(f"{read.label} names {name}: SCOPE records no rename to {new}")
                continue
            number = int(key[:4])
            where = "a rule or invariant" if name in in_items else "its text"
            suffix = "" if number < 31 else " (an ADR from 0031 has no pending set)"
            problems.append(f"{read.label} cites {name} in {where}: no test, not pending{suffix}")
    return problems


def pending_outside_problems(
    reads: list[Reading], *, defined: set[str], outside: frozenset[str], scope: set[str]
) -> list[str]:
    problems: list[str] = []
    outside_cited: set[str] = set()
    for read in reads:
        outside_cited |= cited(read.full) - cited(read.in_items)
    for name in sorted(outside - scope):
        problems.append(f"outside-rules pending {name} is not named by SCOPE section A")
    for name in sorted(outside - outside_cited):
        problems.append(f"outside-rules pending {name} is no longer cited outside the rules")
    for name in sorted(outside & defined):
        problems.append(f"outside-rules pending {name} exists now; remove it")
    for name in sorted(outside & set().union(*PENDING.values())):
        problems.append(f"{name} is on both the rule pending sets and the outside-rules set")
    return problems


def gate_problems() -> list[str]:
    problems = [f"PENDING[{k!r}] holds {len(v)} names" for k, v in PENDING.items() if v]
    if PENDING_OUTSIDE_RULES:
        problems.append(f"PENDING_OUTSIDE_RULES holds {len(PENDING_OUTSIDE_RULES)} names")
    return problems


# ----------------------------------------------------------------------------------------------
# Mutations of a real ADR text, for the "has teeth" tests
# ----------------------------------------------------------------------------------------------


def drop_item(text: str, label: str, pattern: str) -> str:
    """The text without the item ``label`` (its lines up to the next item or heading)."""
    start = re.search(rf"^{pattern.format(label=re.escape(label))}", text, re.MULTILINE)
    assert start is not None, label
    rest = text[start.start() :]
    nxt = re.search(r"\n(?=\d+\. \*\*|A\d+\. \*\*|- I\w*\d+\. |#{2,3} )", rest[1:])
    stop = start.start() + 1 + (nxt.end() if nxt else len(rest) - 1)
    return text[: start.start()] + text[stop:]


def mutate_each(text: str, spec: AdrSpec) -> dict[str, str]:
    """Named mutants of one ADR text; every one of them must make ``check_adr`` report a problem."""
    first_rule = spec.rule_labels[0]
    last_rule = spec.rule_labels[-1]
    last_inv = spec.invariant_labels[-1]
    first_inv = spec.invariant_labels[0]
    rule_pat = r"{label}\. \*\*"
    inv_pat = r"- {label}\. "
    mid = spec.rule_labels[len(spec.rule_labels) // 2]
    mid_next = spec.rule_labels[len(spec.rule_labels) // 2 + 1]
    mutants: dict[str, str] = {
        "drop the first rule": drop_item(text, first_rule, rule_pat),
        "drop the last rule": drop_item(text, last_rule, rule_pat),
        "drop a middle rule": drop_item(text, mid, rule_pat),
        "drop the first invariant": drop_item(text, first_inv, inv_pat),
        "drop the last invariant": drop_item(text, last_inv, inv_pat),
        "renumber a rule to its neighbour": re.sub(
            rf"^{re.escape(mid_next)}\. \*\*", f"{mid}. **", text, count=1, flags=re.MULTILINE
        ),
        "renumber an invariant": re.sub(
            rf"^- {re.escape(last_inv)}\. ", f"- {first_inv}. ", text, count=1, flags=re.MULTILINE
        ),
        "uncite the first rule": uncite_item(text, first_rule, rule_pat),
        "uncite the last invariant": uncite_item(text, last_inv, inv_pat),
        "cite a name no test defines": add_citation(
            text, mid, rule_pat, "test_zz_no_such_test_anywhere"
        ),
        "cite a name that breaks the naming rule": add_citation(
            text, mid, rule_pat, "test_Capital_Name_Here"
        ),
        "add one rule too many": add_after(
            text, last_rule, rule_pat, f"{_next_label(last_rule)}. **x.** Tests: `test_zz_x`."
        ),
    }
    return mutants


def _next_label(label: str) -> str:
    match = re.fullmatch(r"(A?)(\d+)", label)
    assert match is not None, label
    return f"{match.group(1)}{int(match.group(2)) + 1}"


def add_after(text: str, label: str, pattern: str, line: str) -> str:
    start = re.search(rf"^{pattern.format(label=re.escape(label))}.*$", text, re.MULTILINE)
    assert start is not None, label
    return text[: start.end()] + "\n" + line + text[start.end() :]


MUTANT_NAMES: tuple[str, ...] = (
    "drop the first rule",
    "drop the last rule",
    "drop a middle rule",
    "drop the first invariant",
    "drop the last invariant",
    "renumber a rule to its neighbour",
    "renumber an invariant",
    "uncite the first rule",
    "uncite the last invariant",
    "cite a name no test defines",
    "cite a name that breaks the naming rule",
    "add one rule too many",
)


def uncite_item(text: str, label: str, pattern: str) -> str:
    """The item ``label`` with every backticked test name made invisible to the reader."""
    start = re.search(rf"^{pattern.format(label=re.escape(label))}", text, re.MULTILINE)
    assert start is not None, label
    rest = text[start.start() :]
    nxt = re.search(r"\n(?=\d+\. \*\*|A\d+\. \*\*|- I\w*\d+\. |#{2,3} )", rest[1:])
    stop = start.start() + 1 + (nxt.end() if nxt else len(rest) - 1)
    body = re.sub(r"`(test_\w+)`", r"\1", text[start.start() : stop])
    return text[: start.start()] + body + text[stop:]


def add_citation(text: str, label: str, pattern: str, name: str) -> str:
    start = re.search(rf"^{pattern.format(label=re.escape(label))}.*$", text, re.MULTILINE)
    assert start is not None, label
    return text[: start.end()] + f" Tests: `{name}`." + text[start.end() :]
