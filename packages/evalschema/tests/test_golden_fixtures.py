def _version(text: str) -> tuple[int, int, int]:
    major, minor, patch = (int(part) for part in text.split("."))
    return major, minor, patch


def _unreadable_older(directory: Path) -> list[str]:
    """Names of the fixtures of an older version that do NOT raise ``SchemaVersionMismatch``."""
    errors = api("errors")
    loader = api("loader")
    silent: list[str] = []
    for path in _frozen_documents(directory):
        model = entity_models()[_frozen_entity(path)]
        try:
            loader.load_model(model, path.read_bytes())
        except errors.SchemaVersionMismatch:
            continue
        except Exception as error:  # another error is not the typed one
            silent.append(f"{path.name}: {type(error).__name__}")
        else:
            silent.append(f"{path.name}: parsed")
    return silent


def test_frozen_fixtures_still_parse(tmp_path: Path) -> None:
    """ADR 0008 Decision 5 and I17. (a) The fixtures of the current version parse with the strict
    loader, digests verified. (b) For every older version without a registered upgrade step, each
    fixture raises ``SchemaVersionMismatch``: not another error and never a silent parse. (c) A
    registered ``upgrade()`` step would need its stored twin: none exists in 0.0.1, and this test
    fails when one appears so that the check is extended. The test iterates in its body; with no
    older version the loop is empty, and the controls below prove (b) on a made-up one."""
    loader = api("loader")
    directories = frozen_directories()
    assert [d.name for d in directories].count(CURRENT_SCHEMA_VERSION) == 1
    for holder in (api(""), api("loader")):
        assert not hasattr(holder, "upgrade"), "upgrade() exists: extend this test with check (c)"
    for directory in directories:
        version = _version(directory.name)
        assert version <= _version(CURRENT_SCHEMA_VERSION), f"{directory.name} is newer"
        if directory.name == CURRENT_SCHEMA_VERSION:
            documents = _frozen_documents(directory)
            assert len(documents) == 52
            for path in documents:
                model = entity_models()[_frozen_entity(path)]
                loaded = loader.load_model(model, path.read_bytes())
                assert loaded.schema_version == CURRENT_SCHEMA_VERSION
        else:
            assert _unreadable_older(directory) == [], directory.name

    # controls: the same check on a version that does not exist
    older = tmp_path / "frozen" / "0.0.0"
    older.mkdir(parents=True)
    for path in _frozen_documents(FROZEN):
        document = read_json(path)
        document["schema_version"] = "0.0.0"
        (older / path.name).write_bytes(pretty(document))
    assert _unreadable_older(older) == []
    newer_doc = read_json(FROZEN / "Project.minimal.json")
    newer_doc["schema_version"] = "0.0.2"
    with pytest.raises(api("errors").SchemaVersionTooNew):
        loader.load_model(entity_models()["Project"], pretty(newer_doc))
    # a document that would parse is reported as a silent parse
    silent = tmp_path / "frozen" / "0.0.9"
    silent.mkdir()
    shutil.copy(FROZEN / "Project.minimal.json", silent / "Project.minimal.json")
    assert _unreadable_older(silent) == ["Project.minimal.json: parsed"]


def test_frozen_fixture_dirs_immutable(tmp_path: Path) -> None:
    """ADR 0008 I18: every ``frozen/<version>/`` directory holds exactly the files its
    ``digests.json`` records, with the recorded bytes; a released directory is not edited again
    (a change needs the next version). Controls: a flipped byte, a deleted file and an extra file
    are each reported."""
    directories = frozen_directories()
    assert [d.name for d in directories] == [CURRENT_SCHEMA_VERSION]
    for directory in directories:
        assert frozen_problems(directory) == [], directory.name
    copy = tmp_path / CURRENT_SCHEMA_VERSION
    shutil.copytree(FROZEN, copy)
    assert frozen_problems(copy) == []
    data = bytearray((copy / "Run.maximal.json").read_bytes())
    data[10] ^= 0x01
    (copy / "Run.maximal.json").write_bytes(bytes(data))
    (copy / "Turn.minimal.json").unlink()
    (copy / "Extra.maximal.json").write_text("{}\n", encoding="utf-8")
    problems = frozen_problems(copy)
    assert "[changed] Run.maximal.json" in problems
    assert "[missing] Turn.minimal.json" in problems
    assert "[extra] Extra.maximal.json" in problems
    other = tmp_path / "9.9.9"
    shutil.copytree(FROZEN, other)
    assert any(p.startswith("[version]") for p in frozen_problems(other))
    (copy / "digests.json").unlink()
    assert frozen_problems(copy) == [f"[manifest] {CURRENT_SCHEMA_VERSION}/digests.json is missing"]


