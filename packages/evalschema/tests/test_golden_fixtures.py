def _string_leaves(value: Any, key: str = "") -> Iterator[tuple[str, str]]:
    if isinstance(value, str):
        yield key, value
    elif isinstance(value, dict):
        for name, item in value.items():
            yield from _string_leaves(item, str(name))
    elif isinstance(value, list):
        for item in value:
            yield from _string_leaves(item, key)


def test_no_secrets_or_personal_data_in_fixtures() -> None:
    """Every string of every golden and frozen fixture: no credential pattern of ADR 0007
    Decision 5a (no exception), no high-entropy token except the sealed bytes of the test payloads,
    no real-looking e-mail address, phone number or identifier, no host that is not an
    ``example.*`` domain, and no trace of this repository's owner or machine."""
    credentials = api("credentials")
    paths = sorted(GOLDEN.rglob("*.json")) + sorted(FROZEN.glob("*.json"))
    checked = 0
    for path in paths:
        text = path.read_text(encoding="utf-8")
        for forbidden in FORBIDDEN_SUBSTRINGS:
            assert forbidden not in text, (path.name, forbidden)
        for key, leaf in _string_leaves(json.loads(text)):
            checked += 1
            assert not credentials.contains_credential_pattern(leaf), (path.name, key)
            if key not in CREDENTIAL_FREE_BINARY_FIELDS:
                assert credentials.credential_reason(leaf) is None, (path.name, key)
            if key in OPAQUE_FIELDS or OPAQUE_VALUE.fullmatch(leaf):
                continue  # digests, IDs and sealed bytes are not text: their digits mean nothing
            for what, pattern in PERSONAL.items():
                assert pattern.search(leaf) is None, (path.name, key, what)
            for match in EMAIL.finditer(leaf):
                assert ALLOWED_HOST.match(match.group(1).lower()), (path.name, match.group(0))
            for match in URL.finditer(leaf):
                scheme, host = match.group(1).lower(), match.group(2).lower().split("@")[-1]
                if scheme in ("s3", "gs"):
                    assert host == "tracer-fixtures", (path.name, leaf)
                elif scheme != "file":
                    assert ALLOWED_HOST.match(host.split(":")[0]), (path.name, leaf)
    assert checked > 10_000


