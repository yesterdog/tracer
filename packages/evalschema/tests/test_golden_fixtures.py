def _script(name: str) -> Any:
    """Import ``scripts/<name>.py`` (scripts are not a package)."""
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    assert spec is not None
    assert spec.loader is not None
    module: ModuleType = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _valid_cases() -> list[Any]:
    return [
        pytest.param(entity, path, id=f"{entity}/{path.stem}")
        for entity in ENTITY_NAMES
        for path in golden_valid_files(entity)
    ]


def _invalid_cases() -> list[Any]:
    return [
        pytest.param(entity, path, id=f"{entity}/{path.stem}")
        for entity in ENTITY_NAMES
        for path in golden_invalid_files(entity)
    ]


VALID_CASES = _valid_cases()
INVALID_CASES = _invalid_cases()


def _expected(path: Path) -> dict[str, Any]:
    result: dict[str, Any] = read_json(path.with_name(path.stem + ".expected.json"))
    return result


@functools.cache
def _generated() -> dict[str, bytes]:
    files: dict[str, bytes] = _script("build_golden_fixtures").render()
    return files


@functools.cache
def _exported_schemas() -> dict[str, bytes] | None:
    """The rendered JSON Schema files of ``schema_export`` (None while that module is absent)."""
    if importlib.util.find_spec("tracer_evalschema.schema_export") is None:
        return None
    rendered: dict[str, bytes] = b8.rendered_files()
    return rendered


@functools.cache
def _model_schema_validator(entity: str) -> Any:
    schema = entity_models()[entity].model_json_schema(mode="validation")
    return b8.schema_validator(schema)


@functools.cache
def _exported_schema_validator(entity: str) -> Any:
    files = _exported_schemas()
    if files is None:
        return None
    return b8.schema_validator(json.loads(files[f"{entity}{b8.SCHEMA_SUFFIX}"]))


def _model_schema_rejects(entity: str, document: Any) -> bool:
    return not _model_schema_validator(entity).is_valid(document)


def _exported_schema_rejects(entity: str, document: Any) -> bool | None:
    validator = _exported_schema_validator(entity)
    return None if validator is None else not validator.is_valid(document)


def _first_error(entity: str, document: Any) -> tuple[list[Any], str, str]:
    """(location, kind, message) of the first error; kind is the class name of a typed error."""
    from pydantic import ValidationError

    model = entity_models()[entity]
    try:
        model.model_validate(document)
    except ValidationError as error:
        first = error.errors(include_input=False, include_url=False)[0]
        return list(first["loc"]), str(first["type"]), str(first["msg"])
    except api("errors").TracerSchemaError as error:
        return [], type(error).__name__, str(error)
    raise AssertionError(f"{entity}: the model accepted the document")


