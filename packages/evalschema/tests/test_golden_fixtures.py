@pytest.mark.parametrize("entity", ENTITY_NAMES)
def test_every_entity_has_minimal_maximal_and_three_invalid_fixtures(entity: str) -> None:
    """P1-16: a valid minimal document, a valid maximal document and at least three invalid
    documents, each with its ``expected.json`` (path, kind or tag); nothing else in the
    directory."""
    directory = GOLDEN / entity
    assert sorted(p.name for p in directory.iterdir()) == ["invalid", "valid"]
    names = {p.name for p in (directory / "valid").iterdir()}
    assert {"minimal.json", "maximal.json"} <= names, names
    assert all(n.endswith(".json") for n in names), names
    invalid = golden_invalid_files(entity)
    assert len(invalid) >= 3, f"{entity}: {len(invalid)} invalid fixtures"
    on_disk = {p.name for p in (directory / "invalid").iterdir()}
    expected_names = {p.stem + ".expected.json" for p in invalid}
    assert on_disk == {p.name for p in invalid} | expected_names
    seen: set[tuple[Any, ...]] = set()
    for path in invalid:
        expected = _expected(path)
        assert sorted(expected) == ["error_kind", "error_path", "error_tag", "schema", "why"], path
        assert isinstance(expected["error_path"], list)
        assert isinstance(expected["error_kind"], str)
        assert expected["error_kind"]
        assert expected["error_tag"] is None or re.fullmatch(r"[a-z_]+", expected["error_tag"])
        assert expected["schema"] in ("rejects", "code_only")
        assert isinstance(expected["why"], str)
        assert expected["why"].strip()
        key = (
            tuple(expected["error_path"]),
            expected["error_kind"],
            expected["error_tag"],
            expected["why"],
        )
        assert key not in seen, f"{entity}: two invalid fixtures state the same defect {key}"
        seen.add(key)


def test_the_minimal_and_maximal_fixtures_of_one_entity_differ() -> None:
    """A copy of the minimal document is not a maximal one: the maximal file holds more members
    with a value than the minimal file, for every entity."""

    def filled(value: Any) -> int:
        if isinstance(value, dict):
            return sum(1 + filled(v) for v in value.values() if v not in (None, [], {}))
        if isinstance(value, list):
            return sum(filled(v) for v in value)
        return 0

    for entity in ENTITY_NAMES:
        minimal = read_json(GOLDEN / entity / "valid" / "minimal.json")
        maximal = read_json(GOLDEN / entity / "valid" / "maximal.json")
        assert filled(maximal) > filled(minimal), entity


