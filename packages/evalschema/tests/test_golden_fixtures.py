def test_the_generator_refuses_an_expectation_the_model_does_not_meet(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A fixture can never claim a rejection the model does not make: a wrong error type, a wrong
    location, a missing bracket tag and a document the model accepts each stop the generator."""
    support = importlib.import_module("tests._support_b9")
    invalid = importlib.import_module("tests._support_b9_invalid")
    support.render_all()  # registers the specifications
    extra = [
        ("wrong-kind", [invalid.Set("name", to="")], ["name"], "missing", None),
        ("wrong-path", [invalid.Drop("name")], ["title"], "missing", None),
        ("missing-tag", [invalid.Drop("name")], ["name"], "missing", "tier"),
        ("accepted", [invalid.Set("name", to="Other")], ["name"], "missing", None),
    ]
    for name, edits, path, kind, tag in extra:
        specs = list(support.INVALID["Project"])
        specs.append(
            support.InvalidSpec(
                "Project",
                name,
                invalid.defect("Project", "minimal", *edits),
                tuple(path),
                kind,
                "a deliberately wrong expectation",
                tag,
            )
        )
        monkeypatch.setitem(support.INVALID, "Project", specs)
        with pytest.raises(RuntimeError, match=f"Project/{name}"):
            support.render_all()


def test_golden_generator_check_reports_drift_and_write_repairs_it(tmp_path: Path) -> None:
    """``--check`` finds a changed, a missing and a stale file; ``write`` repairs all three."""
    module = _script("build_golden_fixtures")
    files = _generated()
    root = tmp_path / "fixtures"
    module.write(root, files)
    assert module.compare(root, files) == []
    changed = root / "golden/Project/valid/minimal.json"
    changed.write_bytes(changed.read_bytes().replace(b"Minimal project", b"Other project"))
    (root / "golden/Persona/valid/maximal.json").unlink()
    stale = root / "golden/Project/invalid/not-generated.json"
    stale.write_text("{}\n", encoding="utf-8")
    problems = module.compare(root, files)
    assert "[changed] golden/Project/valid/minimal.json" in problems
    assert "[missing] golden/Persona/valid/maximal.json" in problems
    assert "[stale] golden/Project/invalid/not-generated.json" in problems
    module.write(root, files)
    assert module.compare(root, files) == []
    # README files and a released schema.lock are never touched
    (root / "README.md").write_text("keep\n", encoding="utf-8")
    (root / "frozen" / CURRENT_SCHEMA_VERSION / "schema.lock").write_text("{}\n", encoding="utf-8")
    module.write(root, files)
    assert (root / "README.md").read_text(encoding="utf-8") == "keep\n"
    assert (root / "frozen" / CURRENT_SCHEMA_VERSION / "schema.lock").is_file()


def test_the_deterministic_scope_gives_equal_ids_and_restores_the_generators() -> None:
    """Same label, same IDs and bytes; another label, other values; and nothing stays patched."""
    ids = api("ids")
    original_uuid7, original_urandom = ids.uuid7, os.urandom

    def draw(label: str) -> tuple[list[str], bytes]:
        with scope(label):
            return [str(ids.id_type("run").new()) for _ in range(3)], os.urandom(24)

    first, second, other = draw("a"), draw("a"), draw("b")
    assert first == second
    assert first != other
    assert len(set(first[0])) == 3
    assert ids.uuid7 is original_uuid7
    assert os.urandom is original_urandom
    assert ids.id_type("run").parse(first[0][0]) is not None  # well-formed UUIDv7 text
    assert len({*first[0], *other[0]}) == 6


