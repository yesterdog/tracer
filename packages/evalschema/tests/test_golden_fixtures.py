    labels = [e["schema"] for e in expected]
    assert labels.count("rejects") >= 80
    assert labels.count("code_only") >= 40
    kinds = {e["error_kind"] for e in expected}
    assert {"DigestMismatch", "SchemaVersionTooNew", "SchemaVersionMismatch"} <= kinds
    tags = {e["error_tag"] for e in expected} - {None}
    assert {"tier", "duplicate", "unresolved", "unprotected", "consent", "sealed"} <= tags


