@pytest.mark.parametrize(("entity", "path"), VALID_CASES)
def test_golden_valid_fixtures_round_trip_byte_for_byte(entity: str, path: Path) -> None:
    """File -> strict loader -> model (digests verified for real) -> canonical dump -> the same
    bytes; the JCS bytes of the dump equal those of the file; model -> JSON text -> model is the
    identity (ADR 0008 I14)."""
    model = entity_models()[entity]
    data = path.read_bytes()
    loaded = api("loader").load_model(model, data)
    dumped = loaded.model_dump(mode="json", by_alias=True)
    assert pretty(dumped) == data
    digest_api = api("digest")
    assert digest_api.jcs_bytes(dumped) == digest_api.jcs_bytes(json.loads(data.decode("utf-8")))
    text = loaded.model_dump_json(by_alias=True)
    again = model.model_validate_json(text)
    assert again == loaded
    assert again.model_dump_json(by_alias=True) == text


@pytest.mark.parametrize("entity", ENTITY_NAMES)
def test_golden_minimal_fixture_loads_without_its_null_members(entity: str) -> None:
    """The minimal document is minimal for real: take the explicit nulls away and the model loads
    the rest and dumps the same document (the nulls are the model's own dump of an unset member)."""
    path = GOLDEN / entity / "valid" / "minimal.json"
    document = read_json(path)

    def bare(value: Any) -> Any:
        if isinstance(value, dict):
            return {k: bare(v) for k, v in value.items() if v is not None}
        if isinstance(value, list):
            return [bare(v) for v in value]
        return value

    model = entity_models()[entity]
    dumped = model.model_validate(bare(document)).model_dump(mode="json", by_alias=True)
    assert dumped == document


@pytest.mark.parametrize(("entity", "path"), VALID_CASES)
def test_golden_valid_fixtures_are_accepted_by_the_json_schemas(entity: str, path: Path) -> None:
    """The schema that pydantic generates and the exported file (once ``schema_export`` exists)
    both accept every valid fixture, with ECMA-262 pattern semantics."""
    document = read_json(path)
    assert not _model_schema_rejects(entity, document)
    assert _exported_schema_rejects(entity, document) in (False, None)


def test_golden_json_files_are_strict_utf8_json_in_the_canonical_layout() -> None:
    """Every fixture file is UTF-8 without a byte order mark, strict JSON (no duplicate key, no
    NaN), written by ``pretty()`` (two-space indent, one newline at the end, invisible characters
    as escapes) and free of unescaped invisible characters."""
    loader = api("loader")
    paths = sorted(p for p in GOLDEN.rglob("*.json")) + sorted(p for p in FROZEN.glob("*.json"))
    assert len(paths) > 400
    for path in paths:
        data = path.read_bytes()
        assert not data.startswith(b"\xef\xbb\xbf"), path
        text = data.decode("utf-8")
        document = loader.loads_strict(text)
        assert pretty(document) == data, path
        for char in text:
            assert char.isascii() or char.isprintable(), (path, hex(ord(char)))


