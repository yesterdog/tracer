@pytest.mark.parametrize(("entity", "path"), INVALID_CASES)
def test_golden_invalid_fixtures_are_rejected_with_the_expected_error(
    entity: str, path: Path
) -> None:
    """Pydantic level: the model rejects the document, and its first error has the location and
    the type (or the typed error's class name) that ``expected.json`` states; a bundle rule's
    message starts with its bracketed tag."""
    expected = _expected(path)
    document = api("loader").loads_strict(path.read_bytes())
    location, kind, message = _first_error(entity, document)
    assert location == expected["error_path"], message[:200]
    assert kind == expected["error_kind"], message[:200]
    if expected["error_tag"] is not None:
        assert f"[{expected['error_tag']}]" in message
    # a rejection says what rule it is about without quoting the rejected value of a document that
    # hides its input (the fixtures hold no secret, but the rule is the model's)
    assert message.strip()


@pytest.mark.parametrize(("entity", "path"), INVALID_CASES)
def test_golden_invalid_fixtures_agree_with_the_json_schemas(entity: str, path: Path) -> None:
    """Both validators. ``schema: rejects`` means the exported JSON Schema (the schema pydantic
    generates while ``schema_export`` is absent) rejects the document too; ``schema: code_only``
    means only the model's code can. The label is pinned in both directions: when the schema
    starts to state a rule, the label is stale and this test fails until the fixtures are
    regenerated, so the change is visible. The exported schema is never weaker than the schema
    pydantic generates."""
    expected = _expected(path)
    document = read_json(path)
    model_rejects = _model_schema_rejects(entity, document)
    exported = _exported_schema_rejects(entity, document)
    contract = model_rejects if exported is None else exported
    assert contract == (expected["schema"] == "rejects"), (
        f"{expected['schema']} but the JSON Schema {'rejects' if contract else 'accepts'} it"
    )
    if exported is not None and model_rejects:
        assert exported, "the exported JSON Schema accepts a document the model schema rejects"


def test_golden_invalid_fixtures_cover_both_kinds_of_rejection() -> None:
    """The set is not one-sided: a good part is rejected by the JSON Schema too, a good part only
    by code (cross-record, digest, arithmetic rules), and several errors are typed errors."""
