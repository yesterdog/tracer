def test_property_coverage_exclusions_are_the_unreachable_points_and_nothing_else() -> None:
    """The excluded points are named with a reason, and each exclusion is real: the document that
    would cover the point cannot be valid. (Exclusions that stopped being true would hide
    gaps.)"""
    module = _coverage_module()
    patterns = [pattern for pattern, _reason in module.EXCLUDED]
    assert len(patterns) == 4
    assert all(reason.strip() for _pattern, reason in module.EXCLUDED)

    # exactly these points are excluded, per entity: the five of metadata_flags[] everywhere, the
    # five of a keyed own digest on the versioned entities and the snapshot, and the one plain
    # plaintext digest of the export (a broader exclusion would hide gaps)
    versioned = api("base").VersionedEntity
    for result in module.report(GOLDEN):
        digested = issubclass(entity_models()[result.entity], versioned) or (
            result.entity == "ConfigSnapshot"
        )
        expected = 5 + (5 if digested else 0) + (1 if result.entity == "ExportBundle" else 0)
        assert len(result.excluded) == expected, (result.entity, sorted(result.excluded))

    # 1 and 2: an entity's own content_digest is verified on load, a keyed one cannot be
    persona = read_json(GOLDEN / "Persona" / "valid" / "maximal.json")
    persona["content_digest"] = {
        "scheme": "hmac-sha256-jcs/v1",
        "value": "0" * 64,
        "key_ref": {"key_id": "k1", "key_version": None, "provider_hint": None},
    }
    with pytest.raises(api("errors").DigestKeyUnavailable):
        entity_models()["Persona"].model_validate(persona)

    # 3: a sealed payload's plaintext digest is absent or keyed (P-42)
    export = read_json(GOLDEN / "ExportBundle" / "valid" / "maximal.json")
    sealed = export["sealed_payloads"][0]
