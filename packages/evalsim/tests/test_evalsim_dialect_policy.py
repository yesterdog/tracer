"""P4-16, P4-17, P4-18: the documentation and licensing rules of the three dialects (ADR 0026
rules 1, 3 and 5 and the section "Dialect specifications"; SCOPE amendments BL-298, E-b; contract
``docs/phase4/api-surface-batch-d.md`` section 8). Read repository files and start fresh
interpreters; open no socket.

What these tests do NOT do: they do not pin any item that the ADR marks "not verified" (the proto's
sample format, the rate a deployed bot expects, a Twilio payload size, the WebRTC codec, whether
audio needs the client's data channel, whether aiortc needs the PATCH route). A later verification
may change those items without touching a test.
"""

from __future__ import annotations

import ast
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

from evalsim_support_imports import ADR26, ROOT, SRC, adr_dialect_section, mod  # type: ignore[import-not-found,unused-ignore]

DIALECTS = ("pipecat-protobuf/1", "twilio-media-stream/1", "smallwebrtc/1")
DATE = re.compile(r"\b20[0-9]{2}-[01][0-9]-[0-3][0-9]\b")
URL = re.compile(r"https://[^\s`)>\]]+")


def adr_dialect_block() -> str:
    text: str = ADR26.read_text(encoding="utf-8")
    start = text.index("## Dialect specifications")
    return text[start : text.index("\n## ", start + 5)]


def code_side(dialect_id: str) -> tuple[str, tuple[str, ...], str]:
    """(dialect id, spec sources, retrieved date) as the shipped code states them."""
    if dialect_id == "pipecat-protobuf/1":
        cls = mod("dialects.protobuf_dialect").PipecatProtobufDialect
        return cls.dialect_id, tuple(cls.spec_sources), cls.spec_retrieved
    if dialect_id == "twilio-media-stream/1":
        cls = mod("dialects.twilio").TwilioMediaStreamDialect
        return cls.dialect_id, tuple(cls.spec_sources), cls.spec_retrieved
    w = mod("webrtc")
    return w.DIALECT_ID, tuple(w.SPEC_SOURCES), w.SPEC_RETRIEVED


def test_dialect_spec_cites_docs_with_retrieval_date() -> None:
    block = adr_dialect_block()
    headings = re.findall(r"^### `([^`]+)`", block, re.MULTILINE)
    assert tuple(headings) == DIALECTS  # one subsection per dialect, in the ADR's order
    simtypes = __import__("tracer_evalcore.simtypes", fromlist=["DIALECTS"])
    assert tuple(simtypes.DIALECTS) == DIALECTS
    for dialect_id in DIALECTS:
        section = adr_dialect_section(dialect_id)
        urls = set(URL.findall(section))
        assert urls, f"{dialect_id}: no source URL"
        assert DATE.search(section), f"{dialect_id}: no retrieval date"
        assert "retrieved" in section.lower(), dialect_id
        # the Pipecat sources are read at a tag, never at `main`
        for url in urls:
            if "raw.githubusercontent.com/pipecat-ai/pipecat" in url:
                assert "/v1.14.0/" in url, url
                assert "/main/" not in url, url
        # the code cites the same documents, and only documents the ADR lists
        code_id, sources, retrieved = code_side(dialect_id)
        assert code_id == dialect_id
        assert sources, dialect_id
        assert all(s.startswith("https://") for s in sources), sources
        assert len(set(sources)) == len(sources)
        for source in sources:
            assert any(source == u.rstrip(".,;") for u in urls), (
                f"{dialect_id}: {source} is not in the ADR"
            )
        assert DATE.fullmatch(retrieved), retrieved
        assert retrieved in section, f"{dialect_id}: the code's retrieval date is not the ADR's"
    # the Twilio dialect cites Twilio's pages; the other two cite Pipecat's code
    assert any(
        "twilio.com/docs/voice/media-streams" in s for s in code_side("twilio-media-stream/1")[1]
    )
    assert any("frames/frames.proto" in s for s in code_side("pipecat-protobuf/1")[1])
    assert any("smallwebrtc/request_handler.py" in s for s in code_side("smallwebrtc/1")[1])
    # unverified items stay marked in the ADR (this test pins that the marker exists for the
    # dialects that still have such items, not what the items are)
    assert "not verified" in block


def _generated_problems(name: str, text: str, *, strict_dynamic: bool = False) -> list[str]:
    problems = []
    if re.search(r"_pb2(_grpc)?\.pyi?$|\.proto$", name):
        problems.append("generated file name")
    for needle in (
        "Generated by the protocol buffer compiler",
        "DO NOT EDIT",
        "_descriptor_pool",
        "BuildMessageAndEnumDescriptors",
        "from google.protobuf",
        "import google.protobuf",
        "pipecat.frames.protobufs",
        "frames_pb2",
    ):
        if needle in text:
            problems.append(needle)
    tree = ast.parse(text)
    for node in ast.walk(tree):
        names: list[str] = []
        if isinstance(node, ast.Import):
            names = [a.name for a in node.names]
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            names = [node.module]
        elif isinstance(node, ast.Call):
            fn = node.func
            if getattr(fn, "attr", getattr(fn, "id", "")) in ("import_module", "__import__"):
                arg = node.args[0] if node.args else None
                names = (
                    [arg.value]
                    if isinstance(arg, ast.Constant) and isinstance(arg.value, str)
                    else ["<dynamic>"]
                )
        for imported in names:
            top = imported.split(".")[0]
            banned = {"google", "pipecat", "protobuf", "grpc", "grpcio"}
            if strict_dynamic:
                banned.add("<dynamic>")  # in tracer-evalsim a computed import name is an offence
            if top in banned:
                problems.append(f"import of {imported}")
    return problems


def test_protobuf_codec_is_hand_written_no_generated_or_pipecat_module() -> None:
    """ADR 0026 rules 1, 3, 5 (BL-298; lead decision E-b): the wire format is encoded and decoded
    by hand; no code is generated from ``frames.proto``, no Pipecat module is imported or
    vendored, and ``google.protobuf`` is imported by nothing."""
    codec = SRC / "dialects" / "protobuf_wire.py"
    assert codec.is_file(), "the hand-written codec is tracer_evalsim/dialects/protobuf_wire.py"
    scanned = 0
    for package in ("evalschema", "evaldb", "evalcore", "evalproviders", "cli", "evalsim"):
        root = ROOT / "packages" / package / "src"
        for path in sorted(root.rglob("*")):
            if "__pycache__" in path.parts or not path.is_file():
                continue
            assert "pipecat" not in path.name.lower(), path  # not a vendored or generated module
            assert not re.search(r"_pb2|\.proto$|\.pyi$", path.name) or path.name == "py.typed", (
                path
            )
            if path.suffix == ".py":
                scanned += 1
                strict = package == "evalsim"
                text = path.read_text(encoding="utf-8")
                assert _generated_problems(path.name, text, strict_dynamic=strict) == [], path
    assert scanned > 20
    # the tests themselves are independent of Google's library too (the golden vectors are not
    # its output)
    for path in sorted(Path(__file__).resolve().parent.glob("*.py")):
        if path.name == Path(__file__).name:
            continue
        top = {
            a.name.split(".")[0]
            for n in ast.walk(ast.parse(path.read_text(encoding="utf-8")))
            if isinstance(n, ast.Import)
            for a in n.names
        } | {
            n.module.split(".")[0]
            for n in ast.walk(ast.parse(path.read_text(encoding="utf-8")))
            if isinstance(n, ast.ImportFrom) and n.module
        }
        assert not top & {"google", "pipecat", "protobuf", "grpc"}, path.name
    # a fresh interpreter: importing the codec and both dialects loads no Google, Pipecat, gRPC
    code = (
        "import sys, json\n"
        "import tracer_evalsim.dialects.protobuf_wire\n"
        "import tracer_evalsim.dialects.protobuf_dialect\n"
        "import tracer_evalsim.dialects.twilio\n"
        "banned = ('google', 'pipecat', 'protobuf', 'grpc')\n"
        "bad = sorted(m for m in sys.modules if m.split('.')[0] in banned)\n"
        "print(json.dumps(bad))\n"
    )
    done = subprocess.run(  # noqa: S603
        [sys.executable, "-I", "-c", code], capture_output=True, text=True, timeout=120, check=False
    )
    assert done.returncode == 0, done.stderr
    assert json.loads(done.stdout) == []
    # nothing declares or locks protobuf (the scaffold tests pin the ranges; this pins the reason)
    for pyproject in (ROOT / "packages").glob("*/pyproject.toml"):
        assert "protobuf" not in pyproject.read_text(encoding="utf-8").lower(), pyproject


def test_the_generated_code_scan_has_teeth() -> None:
    bad = [
        ("frames_pb2.py", "x = 1"),
        ("frames.proto", "x = 1"),
        ("a.py", "# Generated by the protocol buffer compiler.  DO NOT EDIT!\nx = 1"),
        ("a.py", "from google.protobuf import message"),
        ("a.py", "import google.protobuf.descriptor_pool"),
        ("a.py", "import pipecat.frames.frames"),
        ("a.py", "from pipecat.serializers.protobuf import ProtobufFrameSerializer"),
        ("a.py", "import importlib\nimportlib.import_module('google.protobuf')"),
        ("a.py", "import importlib\nimportlib.import_module(name)"),
        ("a.py", "__import__('pipecat')"),
        ("a.py", "import grpc"),
        ("a.py", "x = 'pipecat.frames.protobufs.frames_pb2'"),
    ]
    for name, text in bad:
        assert _generated_problems(name, text, strict_dynamic=True), (name, text)
    good = [
        (
            "protobuf_wire.py",
            "import struct\nfrom dataclasses import dataclass\nx = 'frames.proto is documented'",
        ),
        ("b.py", "import websockets\nfrom tracer_evalcore import simtypes"),
    ]
    for name, text in good:
        assert _generated_problems(name, text, strict_dynamic=True) == [], (name, text)


def test_notice_carries_pipecat_bsd2_attribution() -> None:
    """ADR 0026 rule 1: "the BSD-2-Clause attribution is kept with those facts in this ADR and in
    NOTICE when the dialect ships". The seven NOTICE files stay byte-identical (earlier tests pin
    that), so they all carry it."""
    required = (
        "pipecat-ai/pipecat",
        "frames.proto",
        "v1.14.0",
        "Copyright (c) 2024-2026, Daily",
        "BSD-2-Clause",
        "hand-written",
    )
    paths = [ROOT / "NOTICE", *sorted((ROOT / "packages").glob("*/NOTICE"))]
    assert len(paths) >= 7
    texts = {p: p.read_text(encoding="utf-8") for p in paths}
    assert len(set(texts.values())) == 1, "the NOTICE files must stay identical"
    for path, text in texts.items():
        for needle in required:
            assert needle in text, f"{path.relative_to(ROOT)} lacks {needle!r}"
    # the statement is about facts and a hand-written codec: it does not claim copied code
    text = next(iter(texts.values()))
    assert re.search(r"no\s+Pipecat\s+source\s+file\s+is\s+copied", text, re.IGNORECASE), (
        "must say that nothing is copied"
    )
    # the ADR carries the same attribution
    adr = ADR26.read_text(encoding="utf-8")
    assert "Copyright (c) 2024-2026, Daily" in adr
    assert "BSD-2-Clause" in adr


def test_dialect_classes_state_their_ids_codecs_and_rates() -> None:
    proto = mod("dialects.protobuf_dialect").PipecatProtobufDialect
    twilio = mod("dialects.twilio").TwilioMediaStreamDialect
    assert (proto.dialect_id, proto.wire_codec) == ("pipecat-protobuf/1", "pcm_s16le")
    assert (twilio.dialect_id, twilio.wire_codec) == ("twilio-media-stream/1", "mulaw")
    assert twilio(counter=1).sample_rate_hz == 8000
    w = mod("webrtc")
    assert w.DIALECT_ID == "smallwebrtc/1"
    base = mod("dialects.base")
    for cls in (proto, twilio):
        assert issubclass(cls, base.Dialect)
    # the wire codec names are the ones the sim profile schema allows (ADR 0027)
    schema_text = (ROOT / "docs" / "adr" / "0027-simulated-run-records.md").read_text(
        encoding="utf-8"
    )
    for codec in (proto.wire_codec, twilio.wire_codec):
        assert f'"{codec}"' in schema_text


def test_the_dialect_modules_are_named_so_no_wheel_member_contains_pipecat() -> None:
    """The earlier scaffold test refuses any wheel member whose name contains `pipecat`; the
    modules are therefore ``protobuf_dialect`` and ``protobuf_wire`` (contract section 8)."""
    names = sorted(p.relative_to(SRC).as_posix() for p in SRC.rglob("*.py"))
    assert "dialects/protobuf_dialect.py" in names
    assert "dialects/protobuf_wire.py" in names
    assert not [n for n in names if "pipecat" in n.lower()]
    expected: Any = {
        "__init__.py",
        "clock.py",
        "errors.py",
        "limits.py",
        "sender.py",
        "watchdog.py",
        "webrtc.py",
        "ws.py",
        "dialects/__init__.py",
        "dialects/base.py",
        "dialects/protobuf_dialect.py",
        "dialects/protobuf_wire.py",
        "dialects/twilio.py",
    }
    assert expected <= set(names), sorted(expected - set(names))
