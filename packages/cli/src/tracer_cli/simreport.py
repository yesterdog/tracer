"""The single self-contained HTML report of a simulated call (P4-24, ADR 0027 rule 17).

Built by hand like the report of a recorded call (``report.py``), with the same hashed style and
script, the same Content-Security-Policy, the same per-piece escaping of untrusted text and no
external reference. It adds what a simulated call is made of: the stereo player (relative audio by
default; nothing is embedded unless asked), the label "synthetic caller audio" (Sarvam terms
10.2(8)), "outcome not evaluated", the caller and agent intervals on one timeline, the timing table
with its quantum and dialect, the simulator's own reply time apart, usage and cost.
``render_sim_report`` reads the bundle and the audio argument alone: no clock, no file, no
environment, no identifier.
"""

from __future__ import annotations

import base64
from typing import Any, Final

from tracer_cli import simsummary
from tracer_cli.report import (
    SEEK_SCRIPT,
    STYLE,
    EmbeddedAudio,
    RelativeAudio,
    _e,
    _el,
    _none,
    _ut,
    _utc,
    content_security_policy,
)
from tracer_cli.summary import cost_text
from tracer_evalcore.simscore import SIM_AGREEMENT_KEYS, SIM_TIMING_KEYS
from tracer_evalschema.bundle import RunBundle
from tracer_evalschema.transcript import Transcript, Turn

__all__ = ["render_sim_report"]

SYNTHETIC_LABEL: Final = (
    "Synthetic caller audio: the caller's side of the recording (the left channel) is speech "
    "generated by a text-to-speech engine and sent by Tracer. It is not a person speaking."
)
OUTCOME_LABEL: Final = (
    "Outcome not evaluated: this page does not say whether the call reached its goal, and no "
    "verdict is stored."
)


def _transcripts(bundle: RunBundle, source: str) -> tuple[Transcript | None, list[Turn]]:
    held = next((t for t in bundle.transcripts if t.source == source), None)
    if held is None:
        return None, []
    return held, sorted(
        (t for t in bundle.turns if t.transcript_id == held.id), key=lambda t: t.seq
    )


def _header(facts: simsummary.SimFacts) -> str:
    established = facts.outcome["call_established"]
    return "".join(
        [
            _el(
                "header",
                _el("h1", "Tracer: one simulated call")
                + _el(
                    "p",
                    "result: call established" if established else "result: call not established",
                    id="status",
                    data_established="true" if established else "false",
                    data_end_reason=facts.outcome["end_reason"],
                ),
            ),
            _el(
                "section",
                _el(
                    "p",
                    "This page records one call that the synthetic caller of Tracer placed to the "
                    "agent under test. Every timing value was observed at the simulator over "
                    f"{_e(facts.outcome['dialect'])}: it includes the network and the buffering "
                    "of both sides, it is coarse to one frame of the stated quantum, and it is "
                    "not a measurement of the agent alone. Nothing here compares agents or "
                    "dialects.",
                ),
                id="what-this-is",
            ),
            _el("p", _e(SYNTHETIC_LABEL), id="synthetic-label", **{"class": "warning"}),
            _el("p", _e(OUTCOME_LABEL), id="outcome-label"),
            _el(
                "p",
                f"end reason: {_e(facts.outcome['end_reason'])}",
                id="end-reason",
                data_end_reason=facts.outcome["end_reason"],
            ),
        ]
    )


def _audio_section(bundle: RunBundle, audio: RelativeAudio | EmbeddedAudio | None) -> str:
    if not bundle.artifacts or audio is None:
        return _el("section", _el("p", "no recording: the call was not established"), id="audio")
    artifact = bundle.artifacts[0]
    fmt = artifact.audio_format
    assert fmt is not None  # noqa: S101
    parts = [
        _el(
            "p",
            _e(
                f"audio: {fmt.container}, {fmt.sample_rate_hz} Hz, {fmt.channels} channels "
                f"(left: caller, synthetic; right: agent), {artifact.size} bytes, "
                f"sha256 {artifact.sha256}"
            ),
            id="audio-facts",
            data_sha256=artifact.sha256,
            data_bytes=artifact.size,
        )
    ]
    if isinstance(audio, EmbeddedAudio):
        parts.append(
            _el(
                "p",
                "This file contains the call audio. Treat it like the recording: do not share it.",
                id="embed-warning",
                **{"class": "warning"},
            )
        )
        source = "data:audio/wav;base64," + base64.b64encode(audio.data).decode("ascii")
    else:
        source = audio.src
    parts.append(_el("audio", "", id="player", controls="", preload="none", src=source))
    return _el("section", "".join(parts), id="audio")


def _intervals(bundle: RunBundle, facts: simsummary.SimFacts) -> str:
    rows: list[tuple[int, str]] = []
    _, script_turns = _transcripts(bundle, "script")
    for turn in script_turns:
        if turn.start_ms is None or turn.end_ms is None:
            continue
        rows.append((turn.start_ms, _interval_row("caller", turn.seq, turn.start_ms, turn.end_ms)))
    stt, _ = _transcripts(bundle, "our_stt")
    plan = (stt.metadata or {}).get("tracer.chunk_plan") if stt is not None else None
    if isinstance(plan, dict):
        rate = plan["sample_rate_hz"]
        for chunk in plan["chunks"]:
            start = chunk["start_frame"] * 1000 // rate
            end = chunk["end_frame"] * 1000 // rate
            rows.append((start, _interval_row("agent", chunk["index"], start, end)))
    note = ""
    if stt is None:
        note = _el("p", "agent intervals: not available (no speech-to-text of the agent)")
    head = _el(
        "thead", _el("tr", "".join(_el("th", label) for label in ("who", "n", "from", "to", "")))
    )
    body = _el("tbody", "".join(row for _, row in sorted(rows, key=lambda r: r[0])))
    return _el(
        "section",
        _el("h2", "Timeline of the two sides")
        + _el("table", head + body, id="timeline")
        + note
        + _el(
            "p",
            _e(
                f"times in ms on the recording, observed at the simulator over "
                f"{facts.outcome['dialect']}"
            ),
        ),
        id="timeline-section",
    )


def _interval_row(who: str, number: int, start: int, end: int) -> str:
    seek = _el(
        "button",
        f"play {start} to {end} ms",
        type="button",
        data_seek_start_ms=start,
        data_seek_end_ms=end,
        **{"class": "seek"},
    )
    cells = (
        _el("td", who)
        + _el("td", str(number))
        + _el("td", f"{start} ms")
        + _el("td", f"{end} ms")
        + _el("td", seek)
    )
    return _el(
        "tr",
        cells,
        **{
            "class": "interval",
            "data-who": who,
            "data-start-ms": start,
            "data-end-ms": end,
        },
    )


def _timing(facts: simsummary.SimFacts) -> str:
    dialect, quantum = facts.timing["dialect"], facts.timing["quantum_ms"]
    rows = []
    counts = {
        "sim_agent_response_gap_median_ms": facts.timing["gap_n"],
        "sim_barge_in_stop_ms": facts.timing["barge_in_n"],
    }
    for label, text in simsummary.timing_lines(facts):
        rows.append(_el("tr", _el("th", _e(label)) + _el("td", _e(text)), **{"class": "timing"}))
    for key, result in facts.results.items():
        if key not in SIM_TIMING_KEYS:
            continue
        n = counts.get(key)
        attributes: dict[str, Any] = {
            "id": f"timing-{key}",
            "data-status": result.status,
            "data-value": "" if result.value is None else result.value,
            "data-quantum-ms": quantum,
            "data-dialect": dialect,
        }
        if n is not None:
            attributes["data-n"] = n
        rows.append(_el("tr", _el("td", _e(key)), **{"class": "timing-record", **attributes}))
    turn_rows = []
    for turn in facts.timing["turns"]:
        own = turn["self"]
        text = (
            f"gap {turn['gap_ms']} ms, overlap {turn['overlap_ms']} ms, "
            f"stop {turn['barge_in_stop_ms']} ms; the simulator's own time before the line: "
            f"reply {own['reply_ms']} ms (wait {own['wait_ms']}, speech-to-text {own['stt_ms']}, "
            f"brain {own['brain_ms']}, synthesis {own['tts_ms']})"
        )
        turn_rows.append(
            _el(
                "tr",
                _el("th", f"caller turn {turn['turn_seq']}") + _el("td", _e(text)),
                **{"class": "timing-turn", "data-turn-seq": turn["turn_seq"]},
            )
        )
    return _el(
        "section",
        _el("h2", "Timing")
        + _el(
            "p",
            _e(
                f"observed at the simulator over {dialect}; quantum {quantum} ms (the larger of "
                "the caller frame and the longest agent frame received); a median is the "
                "nearest-rank value and shows N."
            ),
            id="timing-note",
        )
        + _el("table", _el("tbody", "".join(rows)), id="timing")
        + _el("table", _el("tbody", "".join(turn_rows)), id="timing-turns"),
        id="timing-section",
    )


def _lines(bundle: RunBundle) -> str:
    _, script_turns = _transcripts(bundle, "script")
    items = []
    for turn in script_turns:
        complete = (turn.metadata or {}).get("tracer.caller_line_complete", True)
        inner = _el("span", "caller", **{"class": "role"}) + _ut("div", "text", turn.text)
        if complete is False:
            inner += _el("span", "cut short by the end of the call", **{"class": "none"})
        items.append(
            _el("li", inner, id=f"caller-{turn.seq}", data_seq=turn.seq, **{"class": "turn"})
        )
    _, stt_turns = _transcripts(bundle, "our_stt")
    heard = []
    for turn in stt_turns:
        inner = _el("span", "agent", **{"class": "role"}) + _ut("div", "text", turn.text)
        heard.append(
            _el("li", inner, id=f"agent-{turn.seq}", data_seq=turn.seq, **{"class": "turn"})
        )
    return _el(
        "section",
        _el("h2", "What the caller said")
        + (_el("ol", "".join(items), id="caller-lines") if items else _none("no line was sent"))
        + _el("h2", "What the speech-to-text heard from the agent")
        + (_el("ol", "".join(heard), id="agent-lines") if heard else _none("nothing transcribed")),
        id="transcripts",
    )


def _agreement(bundle: RunBundle, facts: simsummary.SimFacts) -> str:
    lines = [
        (label, value)
        for label, value in simsummary.sim_summary_lines(bundle)
        if label in ("agreement distance (MER)", "flags", "agreement")
    ]
    mer = facts.results.get(SIM_AGREEMENT_KEYS[0])
    body = "".join(_el("p", _e(f"{label}: {value}")) for label, value in lines)
    return _el(
        "section",
        _el("h2", "Agreement with the agent's own export") + body,
        id="agreement",
        data_status="" if mer is None else mer.status,
    )


def _usage(bundle: RunBundle) -> str:
    rows = "".join(
        _el(
            "tr",
            _el("th", label) + _el("td", _e(simsummary.stage_usage_text(bundle, stage)), id=ident),
        )
        for label, stage, ident in (
            ("synthesis (text to speech)", "sim_caller_tts", "usage-tts"),
            ("caller model", "sim_caller_llm", "usage-llm"),
            ("speech-to-text", "stt", "usage-stt"),
        )
    )
    rows += _el("tr", _el("th", "cost") + _el("td", _e(cost_text(bundle)), id="usage-cost"))
    return _el(
        "section", _el("h2", "Usage and cost") + _el("table", _el("tbody", rows)), id="usage"
    )


def _counts(facts: simsummary.SimFacts) -> str:
    rows = "".join(
        _el("tr", _el("th", _e(name)) + _el("td", str(value)))
        for name, value in facts.outcome["counts"].items()
    )
    return _el("section", _el("h2", "Counts") + _el("table", _el("tbody", rows)), id="counts")


def _warnings(bundle: RunBundle) -> str:
    warnings = bundle.run.ingest_warnings
    items = "".join(
        _el(
            "li",
            _el("code", _e(w.code)) + " " + _ut("span", "", f"{w.path or ''} {w.message or ''}"),
        )
        for w in warnings
    )
    return _el(
        "section",
        _el("p", f"ingest warnings: {len(warnings)}", id="warning-count") + _el("ul", items),
        id="warnings",
        data_count=len(warnings),
    )


def _snapshot_note() -> str:
    return _el(
        "section",
        _el(
            "p",
            "The stored configuration of this run holds a check named "
            "simulated_call_no_outcome_check. It is never run and produces no result. It exists "
            "only because schema 0.0.1 requires such a check, and it is not a judgement of the "
            "agent.",
        ),
        id="snapshot-note",
    )


def render_sim_report(bundle: RunBundle, *, audio: RelativeAudio | EmbeddedAudio | None) -> str:
    if not isinstance(bundle, RunBundle):
        raise TypeError("render_sim_report takes a RunBundle")
    if audio is not None and not isinstance(audio, RelativeAudio | EmbeddedAudio):
        raise TypeError("audio must be a RelativeAudio, an EmbeddedAudio or None")
    facts = simsummary.sim_facts(bundle)
    body = [
        _header(facts),
        _audio_section(bundle, audio),
        _intervals(bundle, facts),
        _timing(facts),
        _lines(bundle),
        _agreement(bundle, facts),
        _usage(bundle),
        _counts(facts),
        _warnings(bundle),
        _snapshot_note(),
        _el("footer", _el("p", f"run created {_utc(bundle.run.created_at)}")),
    ]
    policy = content_security_policy(STYLE, SEEK_SCRIPT, embedded=isinstance(audio, EmbeddedAudio))
    head = (
        '<meta charset="utf-8">'
        + f'<meta http-equiv="Content-Security-Policy" content="{_e(policy)}">'
        + '<meta name="tracer-report" content="1">'
        + "<title>Tracer report</title>"
        + f"<style>{STYLE}</style>"
    )
    main = _el("main", "".join(body), id="report")
    return (
        '<!DOCTYPE html>\n<html lang="en"><head>'
        + head
        + "</head><body>"
        + main
        + f"<script>{SEEK_SCRIPT}</script></body></html>\n"
    )
