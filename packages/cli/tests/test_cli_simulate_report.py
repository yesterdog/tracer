def test_the_report_has_usage_and_cost_for_the_real_engines(tmp_path: Path) -> None:
    files = real_files(tmp_path)
    run = run_sim(files, args=real_args(files), environ=real_env(), transport=SarvamSim())
    doc = parse(run.report())
    cells = {
        n.attrs["id"]: n.text() for n in doc.all("td") if n.attrs.get("id", "").startswith("usage-")
    }
    assert cells["usage-tts"] == "2 requests, 14 characters"
    assert cells["usage-stt"] == "2 requests, 0.3 audio seconds"
    assert cells["usage-cost"] == "not available (no_price_for_model)"
    assert cells["usage-llm"] == "none"


