def test_the_sim_report_keeps_the_structure_rules_and_the_csp(tmp_path: Path) -> None:
    from tracer_cli import report as base

    for name, (raw, _) in reports(tmp_path).items():
        doc = parse(raw)
        assert structure_violations(doc) == [], name
        assert external_request_violations(doc, embedded=False) == [], name
        (meta,) = [n for n in doc.all("meta") if n.attrs.get("http-equiv")]
        directives = csp_directives(meta.attrs["content"])
        style, script = element_text(raw, "style")[0], element_text(raw, "script")[0]
        assert directives["default-src"] == ["'none'"], name
        assert directives["style-src"] == [sha256_source(style)] == [sha256_source(base.STYLE)]
        assert (
            directives["script-src"] == [sha256_source(script)] == [sha256_source(base.SEEK_SCRIPT)]
        )
        assert directives["media-src"] == ["'self'"]
        assert "unsafe-inline" not in meta.attrs["content"]
        assert not ABSOLUTE_PATH.search(raw), name


def test_the_audio_is_a_relative_reference_and_never_embedded_by_default(tmp_path: Path) -> None:
    raw, _ = reports(tmp_path)["ok"]
    doc = parse(raw)
    (player,) = doc.all("audio")
    assert player.attrs["src"] == f"recording-{STAMP}.wav"
    assert (player.attrs["controls"], player.attrs["preload"]) == ("", "none")
    assert "data:audio" not in raw
    assert "base64" not in raw
    assert not doc.all("p") or "embed-warning" not in {n.attrs.get("id") for n in doc.all("p")}
    # a failed call has no recording: no player
    assert parse(reports(tmp_path / "x")["nocall"][0]).all("audio") == []


def test_embedding_the_audio_is_an_explicit_choice_of_the_api() -> None:
    """``render_sim_report`` accepts the Phase 3 ``EmbeddedAudio`` (a later option of the command):
    the CSP then allows ``data:`` media and a warning is shown. No command option exists in Phase
    4."""
    report = mod("report")
    sim = mod("simreport")
    with pytest.raises(TypeError):
        sim.render_sim_report("not a bundle", audio=None)
    parser = mod("cli").build_parser()
    sub = next(a for a in parser._actions if getattr(a, "choices", None))
    assert "--embed-audio" not in {
        o for a in sub.choices["simulate"]._actions for o in a.option_strings
    }
    assert report.EmbeddedAudio(b"RIFF")


def test_the_report_of_the_stored_run_is_the_report_the_command_wrote(tmp_path: Path) -> None:
    """ADR 0027 rule 17: ``render_sim_report`` reads the bundle alone, so the stored bundle gives
    the same bytes (and the report holds no identifier of any record)."""
    files = write_inputs(tmp_path)
    run = run_sim(files)
    written = run.report()
    bundle = run.bundle()
    again = mod("simreport").render_sim_report(
        bundle,
        audio=mod("report").RelativeAudio(f"recording-{STAMP}.wav"),
    )
    assert again == written
    assert str(bundle.id) not in written
    assert str(bundle.run.id) not in written
    assert not re.search(r"\b(?:rbnd|run|tsc|turn|art|use)_[0-9a-f]{8}-", written)
    assert hashlib.sha256(written.encode()).hexdigest()


def test_the_timeline_lists_the_caller_and_the_agent_on_one_scale(tmp_path: Path) -> None:
    raw, _ = reports(tmp_path)["ok"]
    doc = parse(raw)
    table = next(n for n in doc.all("table") if n.attrs.get("id") == "timeline")
    rows = [
        (n.attrs["data-who"], int(n.attrs["data-start-ms"]), int(n.attrs["data-end-ms"]))
        for n in table.all("tr")
        if "interval" in n.classes
    ]
    assert rows == [
        ("caller", 0, 280),
        ("agent", 400, 600),
        ("caller", 880, 1160),
        ("agent", 1100, 1200),
    ]
    buttons = list(table.all("button"))
    assert [b.attrs["data-seek-start-ms"] for b in buttons] == ["0", "400", "880", "1100"]
    # a call whose transcription failed has the caller's side only, and says so
    failed = parse(reports(tmp_path / "f")["sttfail"][0])
    assert "agent intervals: not available" in failed.tracer_text()


def test_the_report_shows_the_lines_and_the_heard_text_escaped_per_piece(tmp_path: Path) -> None:
    """ADR 0017 and ADR 0028 Consequences: hostile agent speech and a hostile scripted line are
    shown as text, each piece in its own isolate, with markers for bidi and control characters;
    nothing breaks out of its element."""
    for k, hostile in enumerate(HOSTILE):
        files = write_inputs(
            tmp_path / f"h{k}",
            evaluator={
                "format": "tracer.sim_evaluator/1",
                "name": "hostile",
                "language": "mr",
                "instructions": "x",
                "expected_outcome": "y",
                "scripted_turns": [{"index": 0, "text": hostile + LINE_0, "language": "mr"}],
                "max_duration_ms": 60_000,
            },
            scenario=scenario_doc(
                [{"wait_ms": 300}, {"speak": {"frames": 5, "level": 1000, "text": hostile}}]
            ),
        )
        (files.root / "stt_replay" / "chunk-0000.json").write_text(
            json.dumps({"request_id": "r", "transcript": hostile, "language_code": "mr-IN"})
        )
        (files.root / "stt_replay" / "chunk-0001.json").unlink()
        run = run_sim(files, target=True)
        assert run.code in (0, 2), (hostile, run.err)
        raw = run.report()
        doc = parse(raw)
        assert structure_violations(doc) == []
        assert external_request_violations(doc, embedded=False) == []
        assert "<script>alert" not in raw
        assert "onerror=" not in raw.replace("onerror=alert", "")
        uts = [n for n in doc.all() if "ut" in n.classes]
        assert uts
        assert all(n.text().startswith(FSI) and n.text().endswith(PDI) for n in uts)
        assert raw.count(FSI) == raw.count(PDI) == len(uts)
        assert not re.search("[\u202a-\u202e\u2066\u2067]", raw)
        caller = next(
            n
            for n in doc.all("div")
            if "ut" in n.classes and n.parent and n.parent.attrs.get("id") == "caller-0"
        )
        assert caller.text()[1:-1] == markerize(hostile + LINE_0)
        heard = next(
            n
            for n in doc.all("div")
            if "ut" in n.classes and n.parent and n.parent.attrs.get("id") == "agent-0"
        )
        assert heard.text()[1:-1] == markerize(hostile)


