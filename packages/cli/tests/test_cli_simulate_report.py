"""P4-24: the HTML report of a simulated call (ADR 0027 rule 17; ADR 0023 amendment A1; ADR 0017;
Sarvam terms 10.2(8), SCOPE finding F4; the Phase 3 batch E report tests as models).

Contract: docs/phase4/api-surface-batch-e.md section 11. The report is a single self-contained file
built by hand: the stereo player (relative audio by default, nothing embedded), the label
"synthetic caller audio", "outcome not evaluated", the caller and agent intervals on one timeline,
the timing table with its quantum and dialect, the simulator's own reply time apart, usage and cost.
It keeps every structure rule of the Phase 3 report (one hashed style, one hashed script, a CSP that
allows nothing else, no external request, untrusted text escaped per piece).
"""

