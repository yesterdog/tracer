def scenario_failed_connection(files: Any) -> Any:
    async def refuse(request: Any) -> Any:
        raise __import__("tracer_evalsim.errors", fromlist=["x"]).SetupFailedError(
            code="connection_refused"
        )

    return run_sim(files, target=True, world_kw={"connect": refuse})


def reports(tmp_path: Path) -> dict[str, tuple[str, Any]]:
    """Reports of the kinds of call: ordinary, silent agent, no connection, failed transcription,
    barge-in, with an export."""
    out: dict[str, tuple[str, Any]] = {}
    ok = write_inputs(tmp_path / "ok")
    run = run_sim(ok, add=["--agent-transcript", str(ok.export), "--declared-language", "mr"])
    out["ok"] = (run.report(), run)
    silent = write_inputs(tmp_path / "silent", scenario=scenario_doc([{"wait_ms": 9000}]))
    run = run_sim(silent)
    out["silent"] = (run.report(), run)
    run = scenario_failed_connection(write_inputs(tmp_path / "nocall"))
    out["nocall"] = (run.report(), run)
    failed = write_inputs(tmp_path / "stt")
    for chunk in (failed.root / "stt_replay").glob("chunk-*.json"):
        chunk.unlink()
    run = run_sim(failed, target=True)
    out["sttfail"] = (run.report(), run)
    barge = write_inputs(
        tmp_path / "barge",
        sim_profile=profile_doc(barge_ins=[{"turn_index": 1, "barge_in_after_ms": 100}]),
        scenario=scenario_doc(
            [{"wait_ms": 300}, {"speak": {"frames": 30, "level": 1000, "text": HEARD_0}}]
        ),
    )
    run = run_sim(barge)
    out["barge"] = (run.report(), run)
    return out


def test_sim_report_labels_synthetic_audio(tmp_path: Path) -> None:
    """Sarvam terms 10.2(8), ADR 0026 rule 21 and invariant IA1: every output that can be taken for
    a recording of a person says that the caller's side is synthetic. The report, whatever the
    outcome, has the label; so has the result block of the command."""
    for name, (report, run) in reports(tmp_path).items():
        doc = parse(report)
        (label,) = [n for n in doc.all("p") if n.attrs.get("id") == "synthetic-label"]
        text = label.text()
        assert "Synthetic caller audio" in text, name
        assert "not a person" in text, name
        assert "generated by a text-to-speech engine" in text, name
        assert "caller audio: synthetic (generated speech, not a person)" in run.out, name
    audio_label = parse(reports(tmp_path / "again")["ok"][0])
    facts = [n for n in audio_label.all("p") if n.attrs.get("id") == "audio-facts"]
    assert facts
    assert "left: caller, synthetic" in facts[0].text()


def test_sim_report_states_outcome_not_evaluated(tmp_path: Path) -> None:
    """ADR 0027 rule 12, finding F7: the report says the outcome was not evaluated and names the
    inert check; no verdict, pass or fail is shown for the call."""
    for name, (report, run) in reports(tmp_path).items():
        doc = parse(report)
        (outcome,) = [n for n in doc.all("p") if n.attrs.get("id") == "outcome-label"]
        assert outcome.text().startswith("Outcome not evaluated"), name
        assert "no verdict is stored" in outcome.text()
        note = next(n for n in doc.all("section") if n.attrs.get("id") == "snapshot-note").text()
        assert "simulated_call_no_outcome_check" in note
        assert "never run" in note
        assert "not a judgement of the agent" in note
        assert "schema 0.0.1" in note
        assert "outcome: not evaluated" in run.out
        text = doc.tracer_text().lower()
        assert not re.search(r"\b(passed|failed|success|verdict:)", text), name
    bundle = reports(tmp_path / "second")["ok"][1].bundle()
    assert bundle.verdict is None


def test_sim_report_timing_shows_quantum_and_dialect(tmp_path: Path) -> None:
    """ADR 0027 rule 10 and invariant I5, ADR 0023 A1: each timing value is shown as what it is,
    with "observed at the simulator over <dialect>", its quantum and N for a median; a value
    without both edges says which edge is missing and is never 0; the simulator's own time is a
    separate table."""
    built = reports(tmp_path)
    doc = parse(built["ok"][0])
    table = next(n for n in doc.all("table") if n.attrs.get("id") == "timing")
    rows = {n.attrs["id"]: n for n in table.all("tr") if "timing-record" in n.classes}
    gap = rows["timing-sim_agent_response_gap_median_ms"]
    assert gap.attrs["data-dialect"] == "pipecat-protobuf/1"
    assert gap.attrs["data-quantum-ms"] == "20"
    assert gap.attrs["data-n"] == "2"
    assert gap.attrs["data-value"] == "0"
    assert gap.attrs["data-status"] == "scored"
    first = rows["timing-sim_first_agent_audio_ms"]
    assert first.attrs["data-value"] == "400"
    assert "data-n" not in first.attrs
    shown = {
        n.all("th")[0].text(): n.all("td")[0].text()
        for n in table.all("tr")
        if "timing" in n.classes
    }
    assert shown["first agent audio"] == (
        "400 ms (observed at the simulator over pipecat-protobuf/1, quantum 20 ms)"
    )
    assert shown["gap after the caller's line (median)"].endswith("quantum 20 ms, N 2)")
    note = next(n for n in doc.all("p") if n.attrs.get("id") == "timing-note").text()
    assert "observed at the simulator over pipecat-protobuf/1" in note
    assert "quantum 20 ms" in note
    assert "not a measurement of the agent alone" in doc.tracer_text()
    # per caller turn, with the simulator's own time apart
    turns = next(n for n in doc.all("table") if n.attrs.get("id") == "timing-turns")
    first_turn = turns.all("td")[0].text()
    assert first_turn.startswith("gap 120 ms, overlap 0 ms, stop None ms; the simulator's own time")
    # a value without both edges is not 0
    silent = parse(built["silent"][0])
    srow = next(
        n for n in silent.all("tr") if n.attrs.get("id") == "timing-sim_first_agent_audio_ms"
    )
    assert srow.attrs["data-status"] == "error"
    assert srow.attrs["data-value"] == ""
    stext = next(n for n in silent.all("table") if n.attrs.get("id") == "timing").text()
    assert "not measured (missing edge: first active agent frame)" in stext
    twilio = write_inputs(tmp_path / "tw", sim_profile=profile_doc("twilio-media-stream/1"))
    tw = parse(run_sim(twilio).report())
    assert (
        next(
            n for n in tw.all("tr") if n.attrs.get("id") == "timing-sim_first_agent_audio_ms"
        ).attrs["data-dialect"]
        == "twilio-media-stream/1"
    )
    # the barge-in value appears only for a profile that schedules one, with its N
    barge = parse(built["barge"][0])
    assert any(n.attrs.get("id") == "timing-sim_barge_in_stop_ms" for n in barge.all("tr"))
    assert not any(n.attrs.get("id") == "timing-sim_barge_in_stop_ms" for n in doc.all("tr"))


def test_sim_report_never_claims_accuracy_or_quality(tmp_path: Path) -> None:
    """ADR 0023 amendment A1 and invariant IA1: the Tracer-written text and attribute values of the
    report hold none of the claim words (rule 1 and A1), nor a recommendation."""
    for name, (report, _) in reports(tmp_path).items():
        doc = parse(report)
        outside = doc.tracer_text()
        assert not DENY.search(outside), (name, DENY.findall(outside))
        assert not re.search(r"(?i)\b(recommend|suggest)", outside), name
        for node in doc.all():
            for key, value in node.attrs.items():
                if key not in ("src", "content"):
                    assert not DENY.search(value), (name, key, value)
        assert "agreement distance (MER)" in outside or "agreement" in outside


