"""Render the field reference ``docs/schema/*.md`` from the shipped JSON Schema files (P1-20a).

The pages are generated, never edited by hand (ADR 0008 Decision 9). The only input is the
committed package data ``tracer_evalschema/schemas/`` (the ``*.schema.json`` files and
``schema.lock``); the models are not imported for rendering, so the pages say exactly what the
exported schemas say. Rules that JSON Schema cannot state are not in the schemas and therefore
not on these pages: ``SCHEMA_POLICY.md`` explains where they live.

Usage (from the repository root)::

    uv run --locked python scripts/generate_field_docs.py --write   # regenerate docs/schema/
    uv run --locked python scripts/generate_field_docs.py --check   # exit 1 on any drift (CI)

``--check`` prints one tagged line per problem to stderr (``[changed] <name>``, ``[missing]
<name>``, ``[extra] <name>``, ``[lock] <detail>``) and exits 1; it exits 0 with no output when
the directory equals the rendered pages. A usage error exits 2. Output is LF-terminated UTF-8
and depends only on the schema bytes, so every Python version renders the same bytes.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from tracer_evalschema.digest import sha256_hex
from tracer_evalschema.schema_export import LOCK_NAME, SCHEMA_SUFFIX, schema_directory

ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = ROOT / "docs" / "schema"
INDEX_NAME = "README.md"
VALUE_OBJECTS_NAME = "value-objects.md"
LONG_PATTERN = 100
MAX_SAFE_INTEGER = 2**53 - 1

GENERATED_NOTE = (
    "<!-- Generated by scripts/generate_field_docs.py from the shipped JSON Schema files. "
    "Do not edit by hand: run `uv run --locked python scripts/generate_field_docs.py --write`. -->"
)

JsonObject = dict[str, Any]


# ------------------------------------------------------------------------------ loading


def load_schemas(directory: Path) -> tuple[dict[str, JsonObject], JsonObject]:
    """Read ``schema.lock`` and every schema file it lists, after checking each file's SHA-256
    against the lock. Returns ``({class name: schema}, lock)``. Raises ``ValueError`` when the
    lock is missing or malformed, a listed file is missing, a hash differs, or a schema file is
    not listed (the shipped directory must be consistent before docs are rendered from it)."""
    lock_path = directory / LOCK_NAME
    if not lock_path.is_file():
        raise ValueError(f"[lock] {LOCK_NAME} is missing")
    lock = json.loads(lock_path.read_bytes())
    files = lock.get("files")
    if not isinstance(files, dict) or not isinstance(lock.get("schema_version"), str):
        raise ValueError(f"[lock] {LOCK_NAME} has no files or no schema_version")
    on_disk = sorted(p.name for p in directory.glob("*" + SCHEMA_SUFFIX) if p.is_file())
    if on_disk != sorted(files):
        raise ValueError(f"[lock] the schema files differ from the files {LOCK_NAME} lists")
    schemas: dict[str, JsonObject] = {}
    for name in sorted(files):
        data = (directory / name).read_bytes()
        if sha256_hex(data) != files[name]:
            raise ValueError(f"[lock] {name} does not match its hash in {LOCK_NAME}")
        document = json.loads(data)
        title = document.get("title")
        if name != f"{title}{SCHEMA_SUFFIX}":
            raise ValueError(f"[lock] {name} has the title {title!r}")
        schemas[title] = document
    return schemas, lock


# ------------------------------------------------------------------------------ helpers


def anchor(name: str) -> str:
    """The GitHub heading anchor of a value-object section (``## Name``)."""
    return name.lower()


def link(name: str, entities: Mapping[str, JsonObject]) -> str:
    if name in entities:
        return f"[{name}]({name}.md)"
    return f"[{name}]({VALUE_OBJECTS_NAME}#{anchor(name)})"


def code(text: str) -> str:
    """An inline code span that survives a GitHub table cell (``|`` escaped)."""
    fence = "``" if "`" in text else "`"
    pad = " " if "`" in text else ""
    return f"{fence}{pad}{text.replace('|', chr(92) + '|')}{pad}{fence}"


def literal(value: Any) -> str:
    return code(json.dumps(value, ensure_ascii=False, sort_keys=True))


def ref_name(ref: str) -> str:
    prefix = "#/$defs/"
    if not ref.startswith(prefix):
        raise ValueError(f"non-local reference {ref!r}")
    return ref[len(prefix) :]


def scalar_facets(schema: Mapping[str, Any]) -> list[str]:
    facets: list[str] = []
    if "pattern" in schema:
        pattern = str(schema["pattern"])
        if len(pattern) > LONG_PATTERN:
            facets.append(f"pattern of {len(pattern)} characters (see the schema file)")
        else:
            facets.append("pattern " + code(pattern))
    if "format" in schema:
        facets.append("format " + code(str(schema["format"])))
    for key, label in (
        ("minLength", "at least {} characters"),
        ("maxLength", "at most {} characters"),
        ("minimum", "minimum {}"),
        ("exclusiveMinimum", "greater than {}"),
        ("maximum", "maximum {}"),
        ("minItems", "at least {} items"),
        ("maxItems", "at most {} items"),
        ("minProperties", "at least {} members"),
    ):
        if key in schema:
            value = schema[key]
            text = "2**53 - 1" if value == MAX_SAFE_INTEGER else json.dumps(value)
            facets.append(label.format(text))
    if schema.get("uniqueItems") is True:
        facets.append("no repeated items (`uniqueItems`)")
    return facets


def describe(schema: Mapping[str, Any], entities: Mapping[str, JsonObject]) -> str:
    """One line that states the type and the constraints of a property schema."""
    if "$ref" in schema:
        return link(ref_name(str(schema["$ref"])), entities)
    if "enum" in schema:
        members = ", ".join(literal(m) for m in schema["enum"])
        return f"one of {members}"
    if "anyOf" in schema:
        return " or ".join(describe(branch, entities) for branch in schema["anyOf"])
    if "oneOf" in schema:
        return "exactly one of: " + "; ".join(describe(b, entities) for b in schema["oneOf"])
    kind = schema.get("type")
    facets = scalar_facets(schema)
    if kind == "array":
        items = schema.get("items")
        text = "array" if items is None else "array of " + describe(items, entities)
    elif kind == "object":
        text = "object"
        if "patternProperties" in schema:
            parts = [
                f"keys matching {code(str(key))} with values {describe(value, entities)}"
                for key, value in sorted(schema["patternProperties"].items())
            ]
            text = "object with " + "; ".join(parts)
            if schema.get("additionalProperties") is False:
                text += ", no other keys"
        elif schema.get("additionalProperties") is True and "properties" not in schema:
            text = "object with any JSON members"
        elif "properties" in schema:
            text = "object (inline; see the schema file)"
    elif isinstance(kind, str):
        text = code(kind)
    elif isinstance(kind, list):
        text = " or ".join(code(str(k)) for k in kind)
    else:
        text = "any JSON value"
    if facets:
        text += " (" + "; ".join(facets) + ")"
    return text


def references(value: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(value, dict):
        for key, inner in value.items():
            if key == "$ref" and isinstance(inner, str):
                found.add(ref_name(inner))
            else:
                found |= references(inner)
    elif isinstance(value, list):
        for inner in value:
            found |= references(inner)
    return found


def first_paragraph(text: str) -> str:
    paragraph = text.strip().split("\n\n", 1)[0]
    return " ".join(paragraph.split())


def id_prefix(schema: Mapping[str, Any]) -> str | None:
    pattern = schema.get("properties", {}).get("id", {}).get("pattern")
    if isinstance(pattern, str) and pattern.startswith("^") and "_" in pattern:
        head = pattern[1 : pattern.index("_")]
        if head.isalpha() and head.islower():
            return head
    return None


def object_section(
    schema: Mapping[str, Any], entities: Mapping[str, JsonObject], level: str
) -> list[str]:
    """Description, field table and conditional rules of one object schema."""
    lines: list[str] = []
    description = str(schema.get("description", "")).strip()
    lines += [f"{level} Description", ""]
    lines += [description if description else "(The schema has no description.)", ""]
    properties: Mapping[str, Any] = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines += [f"{level} Fields", ""]
    if properties:
        lines += [
            "| Field | Required | Type and constraints | Default | Notes |",
            "| --- | --- | --- | --- | --- |",
        ]
        for name in sorted(properties):
            prop = properties[name]
            notes = []
            if prop.get("x-pii") is True:
                notes.append("personal data (`x-pii`)")
            default = literal(prop["default"]) if "default" in prop else ""
            lines.append(
                f"| {code(name)} | {'yes' if name in required else 'no'} | "
                f"{describe(prop, entities)} | {default} | {'; '.join(notes)} |"
            )
        lines.append("")
    else:
        lines += ["(No properties.)", ""]
    extra = schema.get("additionalProperties")
    if extra is False:
        lines += ["Members not listed above are rejected (`additionalProperties: false`).", ""]
    rules = schema.get("allOf")
    if rules:
        lines += [
            f"{level} Conditional rules",
            "",
            "The schema states these conditional rules as `allOf` of `if`/`then` (copied "
            "verbatim from the schema file).",
            "",
            "```json",
            json.dumps(rules, indent=2, sort_keys=True, ensure_ascii=False),
            "```",
            "",
        ]
    return lines


# ------------------------------------------------------------------------------ rendering


def check_embedded_entities(schemas: Mapping[str, JsonObject]) -> None:
    """An entity embedded under ``$defs`` of another file must be the entity's own schema
    (without ``$id``, ``$schema`` and ``$defs``); otherwise one page could not describe both."""
    for owner, document in schemas.items():
        for name, definition in document.get("$defs", {}).items():
            if name in schemas:
                own = {
                    k: v for k, v in schemas[name].items() if k not in {"$id", "$schema", "$defs"}
                }
                if own != definition:
                    raise ValueError(f"$defs/{name} of {owner} differs from {name}.schema.json")


def collect_value_objects(
    schemas: Mapping[str, JsonObject],
) -> tuple[dict[str, JsonObject], dict[str, set[str]]]:
    definitions: dict[str, JsonObject] = {}
    used_by: dict[str, set[str]] = {}
    for owner, document in schemas.items():
        for name, definition in document.get("$defs", {}).items():
            if name in schemas:
                continue
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"$defs/{name} differs between schema files")
            definitions[name] = definition
            used_by.setdefault(name, set()).add(owner)
    names = [anchor(n) for n in definitions]
    if len(names) != len(set(names)):
        raise ValueError("two value objects share a heading anchor")
    return definitions, used_by


def render_entity(
    name: str, schema: JsonObject, lock: Mapping[str, Any], schemas: Mapping[str, JsonObject]
) -> str:
    file_name = f"{name}{SCHEMA_SUFFIX}"
    prefix = id_prefix(schema)
    versioned = "version" in schema.get("properties", {})
    lines = [GENERATED_NOTE, "", f"# {name}", ""]
    lines += [
        f"- Schema file: `{file_name}` (package data `tracer_evalschema/schemas/`)",
        f"- `$id`: `{schema.get('$id')}`",
        f"- Schema version: `{lock['schema_version']}`",
        f"- SHA-256 of the schema file (as in `{LOCK_NAME}`): `{lock['files'][file_name]}`",
        f"- ID prefix: `{prefix}`" if prefix else "- ID prefix: (no `id` pattern found)",
        "- Versioned (has `version`): " + ("yes" if versioned else "no"),
        "",
    ]
    lines += object_section(schema, schemas, "##")
    own_props = {k: v for k, v in schema.items() if k != "$defs"}
    direct = sorted(references(own_props))
    if direct:
        lines += ["## Types used directly", ""]
        lines += [f"- {link(n, schemas)}" for n in direct]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_value_objects(
    definitions: Mapping[str, JsonObject],
    used_by: Mapping[str, set[str]],
    lock: Mapping[str, Any],
    schemas: Mapping[str, JsonObject],
) -> str:
    lines = [GENERATED_NOTE, "", "# Value objects", ""]
    lines += [
        "Value objects have no file of their own: each travels under `$defs` of every entity "
        "schema that embeds it, with the same content in every file. They carry no `id`, "
        f"`schema_version`, `created_at` or `metadata`. Schema version `{lock['schema_version']}`.",
        "",
    ]
    for name in sorted(definitions):
        definition = definitions[name]
        lines += [f"## {name}", ""]
        users = ", ".join(link(u, schemas) for u in sorted(used_by[name]))
        lines += [f"Embedded in: {users}", ""]
        lines += object_section(definition, schemas, "###")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_index(
    schemas: Mapping[str, JsonObject],
    definitions: Mapping[str, JsonObject],
    lock: Mapping[str, Any],
) -> str:
    lines = [GENERATED_NOTE, "", "# Field reference", ""]
    lines += [
        f"Schema version `{lock['schema_version']}`. One page per entity, generated from the "
        "JSON Schema file of that entity, and one page for the value objects. The JSON Schema "
        "files are the exported contract; the pydantic models enforce further rules that JSON "
        "Schema cannot state (cross-record, arithmetic, cryptographic and content rules). "
        "`SCHEMA_POLICY.md` (in `packages/evalschema/`) describes those rules and where they "
        "are listed.",
        "",
        "## Entities",
        "",
        "| Entity | ID prefix | Versioned | Summary |",
        "| --- | --- | --- | --- |",
    ]
    for name in sorted(schemas):
        schema = schemas[name]
        prefix = id_prefix(schema)
        versioned = "yes" if "version" in schema.get("properties", {}) else "no"
        summary = first_paragraph(str(schema.get("description", ""))).replace("|", "\\|")
        lines.append(
            f"| [{name}]({name}.md) | {code(prefix) if prefix else ''} | {versioned} | {summary} |"
        )
    lines += ["", "## Value objects", ""]
    lines += [f"- {link(n, schemas)}" for n in sorted(definitions)]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_docs(schemas: Mapping[str, JsonObject], lock: Mapping[str, Any]) -> dict[str, str]:
    """File name -> page text for ``docs/schema/``. Pure; sorted by file name."""
    check_embedded_entities(schemas)
    definitions, used_by = collect_value_objects(schemas)
    pages: dict[str, str] = {}
    for name in sorted(schemas):
        pages[f"{name}.md"] = render_entity(name, schemas[name], lock, schemas)
    pages[VALUE_OBJECTS_NAME] = render_value_objects(definitions, used_by, lock, schemas)
    pages[INDEX_NAME] = render_index(schemas, definitions, lock)
    if len(pages) != len(schemas) + 2:
        raise ValueError("a page name collides with an entity page")
    return dict(sorted(pages.items()))


def render_from_directory(directory: Path) -> dict[str, bytes]:
    schemas, lock = load_schemas(directory)
    return {name: text.encode("utf-8") for name, text in render_docs(schemas, lock).items()}


# ------------------------------------------------------------------------------ write, check


def write_docs(pages: Mapping[str, bytes], out_dir: Path) -> list[str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in sorted(out_dir.glob("*.md")):
        if stale.is_file() and stale.name not in pages:
            stale.unlink()
    for name, data in pages.items():
        path = out_dir / name
        if not path.is_file() or path.read_bytes() != data:
            path.write_bytes(data)
    return sorted(pages)


def check_docs(pages: Mapping[str, bytes], out_dir: Path) -> list[str]:
    problems: list[str] = []
    present = {p.name: p for p in out_dir.iterdir()} if out_dir.is_dir() else {}
    for name, data in pages.items():
        path = present.get(name)
        if path is None or not path.is_file() or path.is_symlink():
            problems.append(f"[missing] {name}")
        elif path.read_bytes() != data:
            problems.append(f"[changed] {name}")
    problems += [f"[extra] {name}" for name in sorted(present) if name not in pages]
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="generate_field_docs.py",
        description="Render docs/schema/*.md from the shipped JSON Schema files.",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the pages")
    mode.add_argument("--check", action="store_true", help="exit 1 when the pages are stale")
    parser.add_argument("--out", default=None, help="output directory (default: docs/schema)")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return int(exc.code) if isinstance(exc.code, int) else 2
    out_dir = Path(args.out) if args.out else DOCS_DIR
    try:
        pages = render_from_directory(schema_directory())
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    if args.write:
        written = write_docs(pages, out_dir)
        print(f"wrote {len(written)} field reference pages")
        return 0
    problems = check_docs(pages, out_dir)
    for line in problems:
        print(line, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
