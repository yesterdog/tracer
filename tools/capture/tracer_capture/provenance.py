"""provenance.json writer."""

from __future__ import annotations

import datetime as dt
import hashlib
import importlib.metadata as md
import json
import platform
from pathlib import Path
from typing import Any

from tracer_capture.models import ModelRecord

PACKAGES = [
    "pipecat-ai",
    "opentelemetry-api",
    "opentelemetry-sdk",
    "faster-whisper",
    "ctranslate2",
    "kokoro-onnx",
    "espeakng-loader",
    "onnxruntime",
    "mlx",
    "mlx-lm",
    "mlx-whisper",
    "phonemizer",
    "soxr",
    "openai",
    "numpy",
    "soundfile",
]

# Licences as declared in each distribution's metadata at the pinned version (read at run time).
_FILES = {
    "f1_spans.otlp.json": "F1 Pipecat OTel spans (OTLP/JSON)",
    "f4_conversation.json": "F4 EvalConversationObserver conversation file",
    "f6_stereo.wav": "F6 AudioBufferProcessor stereo recording (left user, right bot)",
    "f7_turn_events.jsonl": "F7 turn-event log (Pipecat event payloads, one JSON object per line)",
}


# Distributions whose metadata declares no licence; value checked against the upstream
# repository's licence file (GitHub licence API, 2026-10-23), not guessed.
_UPSTREAM = {
    "kokoro-onnx": "MIT (not declared in metadata; upstream repo thewh1teagle/kokoro-onnx)",
    "espeakng-loader": (
        "MIT wrapper (not declared in metadata; upstream repo thewh1teagle/espeakng-loader); "
        "it bundles libespeak-ng, GPL-3.0"
    ),
}


def _licence(dist: str) -> str:
    meta = md.metadata(dist)
    fields = meta.json
    declared = fields.get("license_expression") or fields.get("license")
    if declared:
        return declared if isinstance(declared, str) else "; ".join(declared)
    return _UPSTREAM.get(dist, "undeclared in metadata")


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_provenance(
    out: Path,
    scenario_path: Path,
    scenario: dict[str, Any],
    models: list[ModelRecord],
    spans: list[Any],
) -> None:
    prov = {
        "source": "tools/capture harness run against pipecat-ai==1.13.0 (local pipeline)",
        "retrieval_date": dt.datetime.now(dt.UTC).date().isoformat(),
        "method": "captured",
        "scenario": {
            "id": scenario["id"],
            "file": scenario_path.name,
            "language": scenario["language"],
        },
        "scenario_notes": scenario.get("notes"),
        "indic_verified": scenario.get("verified"),
        "software": {
            "python": platform.python_version(),
            "platform": platform.platform(),
            "packages": {p: md.version(p) for p in PACKAGES},
            "package_licences": {p: _licence(p) for p in PACKAGES},
            "notes": [
                "Pipecat is BSD-2-Clause.",
                "Capture-time tools with copyleft licences, none part of any committed artifact "
                "except as the unmodified process that produced the synthetic speech: "
                "phonemizer (GPL-3.0), libespeak-ng bundled by espeakng-loader (GPL-3.0), "
                "soxr (LGPL-2.1-or-later; a Pipecat core dependency). The committed files are "
                "data generated by running them, not copies of their code; a licence review is "
                "still required before release.",
            ],
        },
        "models": [m.as_dict() for m in models],
        "command": (
            "cd tools/capture && uv run python -m tracer_capture.run "
            f"--scenario scenarios/{scenario_path.name} --out <dir> --scratch <dir>"
        ),
        "license": (
            "Apache-2.0 for the scenario text and harness; the audio is synthesized by "
            "Apache-2.0 Kokoro (caller and bot voices). No third-party recordings are included."
        ),
        "pii_status": (
            "none: all text is invented, all speech is synthetic, no identifiable real voice, "
            "no keys; OpenAI-client key is a placeholder string for a loopback server"
        ),
        "span_count": len(spans),
        "harness_added_fields": {
            "f7_turn_events.jsonl": ["seq", "harness_observed_at_utc", "source"],
            "f1_spans.otlp.json": ["span attribute capture.scenario (conversation span)"],
        },
        "files": {
            name: {"description": desc, "sha256": _sha256(out / name)}
            for name, desc in _FILES.items()
        },
    }
    (out / "provenance.json").write_text(
        json.dumps(prov, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
